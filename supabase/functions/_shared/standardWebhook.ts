/**
 * Signature check for Supabase Auth HTTP hooks such as the "Send SMS" hook (auth-sms-hook).
 *
 * Supabase signs every hook call the Standard Webhooks way (https://www.standardwebhooks.com), with the
 * secret shown when the hook is created in the dashboard ("v1,whsec_<base64>"):
 *   webhook-id         unique id of the call
 *   webhook-timestamp  unix seconds
 *   webhook-signature  "v1,<base64 HMAC-SHA256 of '<id>.<timestamp>.<raw body>'>" (several, space separated)
 * Supabase's example verifies with the standardwebhooks package; this is the same check written out,
 * so it has no network import and is unit tested. A call older or newer than WEBHOOK_TOLERANCE_SECONDS
 * is refused, so a recorded call cannot be replayed later.
 *
 * Pure TypeScript (Web Crypto only, available in Deno and Node): unit tested with Vitest.
 */
import { constantTimeEqual } from './smsReplyPayload.ts';

export const WEBHOOK_TOLERANCE_SECONDS = 5 * 60;

// A shorter key cannot be a secret generated by Supabase (they are 32 random bytes or more)
const MIN_KEY_BYTES = 16;

export interface WebhookHeaders {
  id: string | null;
  timestamp: string | null;
  signature: string | null;
}

export type WebhookCheck =
  | { ok: true }
  | { ok: false; reason: 'no_secret' | 'missing_headers' | 'bad_timestamp' | 'expired' | 'bad_signature' };

/** The three Standard Webhooks headers of a request. */
export function webhookHeaders(get: (name: string) => string | null): WebhookHeaders {
  return { id: get('webhook-id'), timestamp: get('webhook-timestamp'), signature: get('webhook-signature') };
}

/** The HMAC key: the base64 part of "v1,whsec_<base64>" ("whsec_<base64>" and bare base64 work too). */
export function webhookSecretKey(secret: string | null | undefined): Uint8Array | null {
  const encoded = (secret ?? '').trim().replace(/^v1,/, '').replace(/^whsec_/, '');
  if (!encoded) return null;
  try {
    const binary = atob(encoded);
    const key = new Uint8Array(binary.length);
    for (let i = 0; i < binary.length; i++) key[i] = binary.charCodeAt(i);
    return key.length >= MIN_KEY_BYTES ? key : null;
  } catch {
    return null;
  }
}

const toBase64 = (bytes: ArrayBuffer): string => {
  let binary = '';
  for (const byte of new Uint8Array(bytes)) binary += String.fromCharCode(byte);
  return btoa(binary);
};

/** Checks that the call really comes from Supabase Auth and is recent. */
export async function verifyWebhook(input: {
  body: string;
  headers: WebhookHeaders;
  secret: string | null | undefined;
  nowSeconds: number;
  subtle?: SubtleCrypto;
}): Promise<WebhookCheck> {
  const key = webhookSecretKey(input.secret);
  if (!key) return { ok: false, reason: 'no_secret' };

  const { id, timestamp, signature } = input.headers;
  if (!id || !timestamp || !signature) return { ok: false, reason: 'missing_headers' };
  if (!/^\d{1,12}$/.test(timestamp.trim())) return { ok: false, reason: 'bad_timestamp' };
  if (Math.abs(input.nowSeconds - Number(timestamp.trim())) > WEBHOOK_TOLERANCE_SECONDS) {
    return { ok: false, reason: 'expired' };
  }

  const subtle = input.subtle ?? globalThis.crypto.subtle;
  const hmacKey = await subtle.importKey('raw', key, { name: 'HMAC', hash: 'SHA-256' }, false, ['sign']);
  const signedContent = new TextEncoder().encode(`${id}.${timestamp.trim()}.${input.body}`);
  const expected = toBase64(await subtle.sign('HMAC', hmacKey, signedContent));

  const presented = signature
    .split(' ')
    .map((part) => part.trim())
    .filter((part) => part.startsWith('v1,'))
    .map((part) => part.slice(3));
  return presented.some((candidate) => constantTimeEqual(candidate, expected))
    ? { ok: true }
    : { ok: false, reason: 'bad_signature' };
}
