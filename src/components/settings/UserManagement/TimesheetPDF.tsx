import React from 'react';
import jsPDF from 'jspdf';
import 'jspdf-autotable';
import { format, parseISO } from 'date-fns';
import { supabase } from '../../../lib/supabase';

interface TimesheetEntry {
  id: string;
  date: string;
  start_time?: string;
  end_time?: string;
  total_hours: number;
  task_description?: string;
  is_overtime: boolean;
}

interface Timesheet {
  id: string;
  user_id: string;
  period_start: string;
  period_end: string;
  total_hours: number;
  regular_hours: number;
  overtime_hours: number;
  status: string;
  user?: {
    full_name: string;
    email: string;
  };
  entries?: TimesheetEntry[];
}

interface PracticeInfo {
  name: string;
  contact_email?: string;
  contact_phone?: string;
  address?: string;
  city?: string;
  country?: string;
  logo_url?: string;
  primary_color?: string;
}

export const generateTimesheetPDF = async (timesheet: Timesheet, practiceInfo?: PracticeInfo) => {
  const pdf = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4'
  });

  const pageWidth = pdf.internal.pageSize.getWidth();
  const pageHeight = pdf.internal.pageSize.getHeight();
  const margin = 20;
  let currentY = margin;

  // Colors based on practice branding
  const primaryColor = practiceInfo?.primary_color || '#0d9488';
  const secondaryColor = '#6b7280';

  // Header
  pdf.setFillColor(primaryColor);
  pdf.rect(0, 0, pageWidth, 25, 'F');

  // Practice Name
  pdf.setTextColor(255, 255, 255);
  pdf.setFontSize(18);
  pdf.setFont('helvetica', 'bold');
  pdf.text(practiceInfo?.name || 'Healthcare Practice', margin, 15);

  // Document Title
  pdf.setTextColor(0, 0, 0);
  pdf.setFontSize(16);
  pdf.setFont('helvetica', 'bold');
  currentY = 40;
  pdf.text('EMPLOYEE TIMESHEET', margin, currentY);

  currentY += 15;

  // Employee Information
  pdf.setFontSize(12);
  pdf.setFont('helvetica', 'normal');
  
  const employeeInfo = [
    ['Employee Name:', timesheet.user?.full_name || 'N/A'],
    ['Email:', timesheet.user?.email || 'N/A'],
    ['Period:', `${format(parseISO(timesheet.period_start), 'MMMM dd, yyyy')} - ${format(parseISO(timesheet.period_end), 'MMMM dd, yyyy')}`],
    ['Status:', timesheet.status.toUpperCase()],
    ['Generated:', format(new Date(), 'MMMM dd, yyyy HH:mm')]
  ];

  employeeInfo.forEach(([label, value]) => {
    pdf.setFont('helvetica', 'bold');
    pdf.text(label, margin, currentY);
    pdf.setFont('helvetica', 'normal');
    pdf.text(value, margin + 35, currentY);
    currentY += 6;
  });

  currentY += 10;

  // Summary Table
  pdf.setFont('helvetica', 'bold');
  pdf.setFontSize(14);
  pdf.text('SUMMARY', margin, currentY);
  currentY += 10;

  const summaryData = [
    ['Total Hours', timesheet.total_hours.toFixed(1)],
    ['Regular Hours', timesheet.regular_hours.toFixed(1)],
    ['Overtime Hours', timesheet.overtime_hours.toFixed(1)]
  ];

  (pdf as any).autoTable({
    startY: currentY,
    head: [['Category', 'Hours']],
    body: summaryData,
    theme: 'grid',
    headStyles: {
      fillColor: primaryColor,
      textColor: 255,
      fontSize: 11,
      fontStyle: 'bold'
    },
    bodyStyles: {
      fontSize: 10
    },
    columnStyles: {
      0: { cellWidth: 60 },
      1: { cellWidth: 30, halign: 'right' }
    },
    margin: { left: margin, right: margin }
  });

  currentY = (pdf as any).lastAutoTable.finalY + 15;

  // Detailed Timesheet Table
  pdf.setFont('helvetica', 'bold');
  pdf.setFontSize(14);
  pdf.text('DETAILED TIMESHEET', margin, currentY);
  currentY += 10;

  // Prepare timesheet data
  const timesheetData = (timesheet.entries || [])
    .sort((a, b) => a.date.localeCompare(b.date))
    .map(entry => [
      format(parseISO(entry.date), 'EEE, MMM dd, yyyy'),
      entry.start_time || '',
      entry.end_time || '',
      entry.total_hours.toFixed(1),
      entry.is_overtime ? 'Yes' : 'No',
      entry.task_description || ''
    ]);

  (pdf as any).autoTable({
    startY: currentY,
    head: [['Date', 'Time In', 'Time Out', 'Hours', 'Overtime', 'Comments']],
    body: timesheetData,
    theme: 'grid',
    headStyles: {
      fillColor: primaryColor,
      textColor: 255,
      fontSize: 10,
      fontStyle: 'bold'
    },
    bodyStyles: {
      fontSize: 9
    },
    columnStyles: {
      0: { cellWidth: 45 },
      1: { cellWidth: 20, halign: 'center' },
      2: { cellWidth: 20, halign: 'center' },
      3: { cellWidth: 15, halign: 'right' },
      4: { cellWidth: 20, halign: 'center' },
      5: { cellWidth: 50 }
    },
    margin: { left: margin, right: margin },
    didDrawPage: function (data: any) {
      // Footer
      const footerY = pageHeight - 15;
      pdf.setFontSize(8);
      pdf.setTextColor(128, 128, 128);
      pdf.text('Generated by HPMS - Healthcare Practice Management System', margin, footerY);
      pdf.text(`Page ${data.pageNumber}`, pageWidth - margin - 15, footerY);
    }
  });

  // Final signature section
  const finalY = (pdf as any).lastAutoTable.finalY + 20;
  
  if (finalY < pageHeight - 60) {
    pdf.setFontSize(12);
    pdf.setTextColor(0, 0, 0);
    pdf.setFont('helvetica', 'bold');
    pdf.text('SIGNATURES', margin, finalY);
    
    const signatureY = finalY + 15;
    pdf.setFont('helvetica', 'normal');
    pdf.setFontSize(10);
    
    // Employee signature line
    pdf.line(margin, signatureY + 15, margin + 70, signatureY + 15);
    pdf.text('Employee Signature', margin, signatureY + 20);
    pdf.text('Date: _______________', margin, signatureY + 25);
    
    // Supervisor signature line
    pdf.line(pageWidth - margin - 70, signatureY + 15, pageWidth - margin, signatureY + 15);
    pdf.text('Supervisor Signature', pageWidth - margin - 70, signatureY + 20);
    pdf.text('Date: _______________', pageWidth - margin - 70, signatureY + 25);
  }

  return pdf;
};

export const downloadTimesheetPDF = async (timesheet: Timesheet) => {
  try {
    // Fetch practice information
    const { data: practiceInfo } = await supabase
      .from('practices')
      .select('name, contact_email, contact_phone, address, city, country, logo_url, primary_color')
      .single();

    const pdf = await generateTimesheetPDF(timesheet, practiceInfo);
    const fileName = `timesheet-${timesheet.user?.full_name?.replace(/\s+/g, '-')}-${format(parseISO(timesheet.period_start), 'yyyy-MM')}.pdf`;
    pdf.save(fileName);
  } catch (error) {
    console.error('Error generating PDF:', error);
    throw error;
  }
};