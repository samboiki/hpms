// A fake Supabase client: each table answers from a queue of results and records what was asked.
// Nothing here reaches a database, an SMS gateway or the invoice service.
const fake = vi.hoisted(() => {
  type Result = { data: unknown; error: unknown };
  const results = new Map<string, Result[]>();
  const calls: { table: string; op: string; args: unknown[] }[] = [];
  const next = (table: string): Result => results.get(table)?.shift() ?? { data: null, error: null };

  // An `or` list keeps a row when one of its parts holds, as PostgREST does (only the filters the visit rule uses)
  const orKeeps = (list: string, row: Record<string, unknown>): boolean =>
    list.split(',').some(part => {
      const [column, operator, ...rest] = part.split('.');
      const value = row[column] ?? null;
      if (operator === 'is' && rest.join('.') === 'null') return value === null;
      if (operator === 'neq') return value !== null && value !== rest.join('.');
      throw new Error(`An or filter this fake does not know: ${part}`);
    });

  class FakeQuery implements PromiseLike<Result> {
    private readonly orLists: string[] = [];
    constructor(private readonly table: string) {}
    private record(op: string, args: unknown[]): this {
      calls.push({ table: this.table, op, args });
      return this;
    }
    select(...args: unknown[]) { return this.record('select', args); }
    eq(...args: unknown[]) { return this.record('eq', args); }
    in(...args: unknown[]) { return this.record('in', args); }
    or(list: string) {
      this.orLists.push(list);
      return this.record('or', [list]);
    }
    order(...args: unknown[]) { return this.record('order', args); }
    limit(...args: unknown[]) { return this.record('limit', args); }
    update(...args: unknown[]) { return this.record('update', args); }
    delete(...args: unknown[]) { return this.record('delete', args); }
    private answer(): Result {
      const result = next(this.table);
      if (this.orLists.length === 0 || !Array.isArray(result.data)) return result;
      return { ...result, data: (result.data as Record<string, unknown>[]).filter(row => this.orLists.every(list => orKeeps(list, row))) };
    }
    maybeSingle() {
      return Promise.resolve(this.answer());
    }
    then<A = Result, B = never>(
      onFulfilled?: ((value: Result) => A | PromiseLike<A>) | null,
      onRejected?: ((reason: unknown) => B | PromiseLike<B>) | null
    ): PromiseLike<A | B> {
      return Promise.resolve(this.answer()).then(onFulfilled, onRejected);
    }
  }

  return {
    results,
    calls,
    rpc: vi.fn(),
    from: (table: string) => new FakeQuery(table),
    createInvoice: vi.fn(),
    sendSMS: vi.fn(),
    sendEmail: vi.fn()
  };
});

vi.mock('../../../lib/supabase', () => ({ supabase: { rpc: fake.rpc, from: fake.from } }));
vi.mock('../../../services/invoiceService', () => ({ invoiceService: { createInvoice: fake.createInvoice } }));
