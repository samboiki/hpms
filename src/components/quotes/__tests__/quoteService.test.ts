// Business rule: before the proposal is applied the screens say "not switched on"; any other database
// problem (another missing table, a permission error) must still be shown as an error.
describe('isQuotesNotEnabledError', () => {
  it.each([
    [{ code: 'PGRST205', message: "Could not find the table 'public.quotes' in the schema cache" }, true],
    [{ code: 'PGRST202', message: 'Could not find the function public.save_quote(p_lines, p_quote) in the schema cache' }, true],
    [{ code: '42P01', message: 'relation "public.billing_code_bundles" does not exist' }, true],
    [{ code: '42P01', message: 'relation "public.patients" does not exist' }, false],
    [{ code: '42501', message: 'new row violates row-level security policy for table "quotes"' }, false],
    [null, false]
  ])('%o -> %s', (error, expected) => {
    expect(isQuotesNotEnabledError(error)).toBe(expected);
  });
});

// Business rule: a quote's totals are always the sum of its lines. The client sends the lines only; the
// database (save_quote) adds them up, so a stale or tampered total can never be stored.
describe('saveQuote', () => {
  it('sends the lines with their teeth and links, and no header totals', async () => {
    fake.rpc.mockResolvedValue({ data: 'q-new', error: null });
    const procedure = line({ lineNo: 1, toothNumbers: ['16'] });
    const material = line({ lineNo: 2, code: '8346', unitPrice: 44.87, totalPrice: 44.87, patientEstimate: 44.87, isAutoGenerated: true, parentLineId: procedure.id, toothNumbers: ['16'] });
    const id = await saveQuote({
      id: null, practiceId: 'p1', patientId: 'pt1', status: 'draft', quoteDate: '2026-10-07', validUntil: '2027-01-05',
      fund: { fundName: null, scheme: null, membershipNumber: null }, estimate: { basis: 'private', note: 'Private' },
      preauthNumber: ' ', fundReference: '', notes: 'Two visits', lines: [procedure, material]
    });
    expect(id).toBe('q-new');
    const [fn, args] = fake.rpc.mock.calls[0];
    expect(fn).toBe('save_quote');
    expect(Object.keys(args.p_quote)).not.toEqual(expect.arrayContaining(['subtotal']));
    expect(args.p_quote).not.toHaveProperty('medical_aid_estimate');
    expect(args.p_quote).toMatchObject({ preauth_number: null, notes: 'Two visits', estimate_basis: 'private' });
    expect(args.p_lines[1]).toMatchObject({ code: '8346', tooth_numbers: '16', parent_line_id: procedure.id, is_auto_generated: true });
    expect(args.p_lines[0].tooth_numbers).toBe('16');
  });

  it('turns a missing save_quote function into "not switched on"', async () => {
    fake.rpc.mockResolvedValue({ data: null, error: { code: 'PGRST202', message: 'Could not find the function public.save_quote in the schema cache' } });
    await expect(
      saveQuote({
        id: null, practiceId: 'p1', patientId: 'pt1', status: 'draft', quoteDate: '2026-10-07', validUntil: '2027-01-05',
        fund: { fundName: null, scheme: null, membershipNumber: null }, estimate: { basis: 'private', note: '' },
        preauthNumber: '', fundReference: '', notes: '', lines: [line({})]
      })
    ).rejects.toThrow('not switched on');
  });
});

// Business rule: an accepted quote becomes exactly one invoice. The quote is read again before the invoice
// is created, and when the link cannot be saved the invoice number is returned so staff link it instead of
// converting again (which would bill the patient twice).
describe('convertQuoteToInvoice', () => {
  const services = [{ id: 's1', code: '8367' }] as unknown as ServiceSelection[];

  it('refuses a quote that someone already invoiced, without creating an invoice', async () => {
    answer('quotes', { data: { status: 'converted' }, error: null });
    await expect(convertQuoteToInvoice({ quote, visitId: 'v1', services })).rejects.toThrow('already been invoiced');
    expect(fake.createInvoice).not.toHaveBeenCalled();
  });

  it('refuses a quote the patient has not accepted', async () => {
    answer('quotes', { data: { status: 'sent' }, error: null });
    await expect(convertQuoteToInvoice({ quote, visitId: 'v1', services })).rejects.toThrow('Only an accepted quote');
    expect(fake.createInvoice).not.toHaveBeenCalled();
  });

  it('creates the invoice for the chosen visit through invoiceService and links the quote to it', async () => {
    answer('quotes', { data: { status: 'accepted' }, error: null }, { data: null, error: null });
    fake.createInvoice.mockResolvedValue({ id: 'inv-1', invoiceNumber: 'INV2610001' });
    const result = await convertQuoteToInvoice({ quote, visitId: 'v1', services });
    expect(fake.createInvoice).toHaveBeenCalledWith({ patientId: 'pt1', visitId: 'v1', services, practiceId: 'p1', notes: 'From quote Q2026-0004' });
    expect(result).toEqual({ invoiceId: 'inv-1', invoiceNumber: 'INV2610001', linkError: null });
    const link = fake.calls.find(call => call.table === 'quotes' && call.op === 'update');
    expect(link?.args[0]).toEqual({ status: 'converted', converted_invoice_id: 'inv-1', converted_visit_id: 'v1' });
  });

  it('returns the invoice and the reason when the link fails, so the quote is linked rather than converted twice', async () => {
    answer('quotes', { data: { status: 'accepted' }, error: null }, { data: null, error: { code: '23514', message: 'The invoice belongs to another patient or practice' } });
    fake.createInvoice.mockResolvedValue({ id: 'inv-2', invoiceNumber: 'INV2610002' });
    expect(await convertQuoteToInvoice({ quote, visitId: 'v1', services })).toEqual({
      invoiceId: 'inv-2',
      invoiceNumber: 'INV2610002',
      linkError: 'The invoice belongs to another patient or practice'
    });
  });
});

// Business rule: a quote is invoiced at a real visit of the patient. A payment plan's, a package's or an opening
// balance's invoices hang on a row the system makes (utils/carrierVisits.ts): it is never offered, even if it were
// not cancelled, so a treatment invoice can never end up on it.
describe('loadConvertibleVisits', () => {
  const visit = (id: string, overrides: Record<string, unknown> = {}) => ({
    id, visit_date: '2026-10-12', visit_type: 'consultation', status: 'completed', chief_complaint: null, is_cancelled: false, automation_source: null, ...overrides
  });

  it('offers the visits without an invoice, never a row that only carries invoices', async () => {
    answer('visits', { data: [visit('v1'), visit('v2'), visit('carrier', { status: 'scheduled', automation_source: CARRIER_VISIT_SOURCE })], error: null });
    answer('invoices_enhanced', { data: [{ visit_id: 'v2' }], error: null });
    const visits = await loadConvertibleVisits('pt1');
    expect(visits.map(item => item.id)).toEqual(['v1']);
    expect(fake.calls.find(call => call.table === 'invoices_enhanced' && call.op === 'in')?.args[1]).toEqual(['v1', 'v2']);
  });
});

// Business rule: quote SMSes go only through the centralized gateway (logged, counted against the
// practice's bundle); a draft becomes "sent" only when the gateway accepted the message.
describe('sendQuoteSms', () => {
  const draft = { ...quote, status: 'draft' as const };

  it('sends through communicationService and then marks the draft as sent by SMS', async () => {
    fake.sendSMS.mockResolvedValue({ success: true, logId: 'log-1', status: 'sent' });
    const result = await sendQuoteSms({ quote: draft, phone: ' 081 000 0000 ', message: ' Your estimate ' });
    expect(result.ok).toBe(true);
    expect(fake.sendSMS).toHaveBeenCalledWith(
      expect.objectContaining({ practiceId: 'p1', patientId: 'pt1', recipientPhone: '081 000 0000', messageContent: 'Your estimate', messageType: 'custom' })
    );
    const update = fake.calls.find(call => call.table === 'quotes' && call.op === 'update');
    expect(update?.args[0]).toMatchObject({ status: 'sent', sent_via: 'sms' });
  });

  it('leaves the quote unchanged when the gateway refuses the message', async () => {
    fake.sendSMS.mockResolvedValue({ success: false, logId: '', status: 'blocked', error: 'SMS_LIMIT_REACHED' });
    expect(await sendQuoteSms({ quote: draft, phone: '0810000000', message: 'x' })).toEqual({ ok: false, message: 'Not sent: SMS_LIMIT_REACHED' });
    expect(fake.calls.some(call => call.op === 'update')).toBe(false);
  });

  it('does not change the status of an accepted quote that is sent again as a copy', async () => {
    fake.sendSMS.mockResolvedValue({ success: true, logId: 'log-2', status: 'sent' });
    await sendQuoteSms({ quote, phone: '0810000000', message: 'Copy' });
    expect(fake.calls.some(call => call.op === 'update')).toBe(false);
  });
});

// Business rule (R28): a quote holds the prices the visit's invoice will get, so the patient's own price rate (a staff,
// private or contract rate) prices the quote as it prices the visit; a quote for a patient whose rate cannot be read
// is not priced at a guess.
describe("a patient's own price rate on a quote", () => {
  const set: TariffSet = {
    practiceId: 'p1',
    practiceType: 'General Practice',
    rows: [{ id: 't-0190', code: '0190', description: 'Consultation', price: '520.00', can_be_multiplied: 'NO', requires_tooth_number: 'NO', is_active: true }],
    book: { rows: [], contracts: [] },
    bookError: null,
    infectionControlStaff: 1
  };

  it('prices the codes at the rate, and at the usual price without one', () => {
    expect(billableOn(set, '2026-10-13', null, { kind: 'staff', percent: 50 })[0]).toMatchObject({ price: 260, patient_rate_percent: 50 });
    expect(billableOn(set, '2026-10-13')[0].price).toBe(520);
  });

  it("reads the patient's rate with the medical aid, and stops when the rate cannot be read", async () => {
    answer('medical_aid_details', { data: [], error: null });
    answer('patient_price_rates', { data: { kind: 'contract', percent: '80.00', set_at: '2026-10-13T08:00:00Z' }, error: null });
    expect(await loadPatientFund('pt1')).toMatchObject({ hasMedicalAid: false, patientRate: { kind: 'contract', percent: 80 } });

    answer('medical_aid_details', { data: [], error: null });
    answer('patient_price_rates', { data: null, error: { code: '57014', message: 'canceling statement due to statement timeout' } });
    await expect(loadPatientFund('pt1')).rejects.toThrow("Could not read the patient's price rate: canceling statement due to statement timeout");
  });

  // Before the rates are in the database every patient is quoted at the usual prices, as before
  it('quotes at the usual prices before the rates are set up', async () => {
    answer('medical_aid_details', { data: [], error: null });
    answer('patient_price_rates', { data: null, error: { code: 'PGRST205', message: "Could not find the table 'public.patient_price_rates' in the schema cache" } });
    expect(await loadPatientFund('pt1')).toMatchObject({ patientRate: null });
  });
});
