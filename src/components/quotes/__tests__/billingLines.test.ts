import { describe, it, expect, vi } from 'vitest';
import { addTariffLines, removeLine, type LineContext } from '../billingLines';
import {
  buildInfectionControlLine,
  buildMaterialFactorLine,
  buildTariffLine
} from '../../visits/visitBillingLines';
import { findInvoiceLineProblems } from '../../../services/invoiceService';
import type { ServiceSelection } from '../../../types/billing';
import { dentalTariffs, tariff } from './quoteTestTariffs';

// invoiceService is imported only for its pure line check; nothing here may reach the database
vi.mock('../../../lib/supabase', () => ({ supabase: {} }));

const tariffs = dentalTariffs();
const context = (overrides: Partial<LineContext> = {}): LineContext => ({
  tariffs,
  hasMedicalAid: true,
  autoInfectionControl: true,
  ...overrides
});

const added = (outcome: ReturnType<typeof addTariffLines>): ServiceSelection[] => {
  if (outcome.status !== 'added') throw new Error(`expected lines, got ${outcome.status}`);
  return outcome.lines;
};

// Ids are random per line, so lines are compared on what is billed
const billed = (lines: readonly ServiceSelection[]) =>
  lines.map(line => ({
    code: line.code,
    description: line.description,
    unitPrice: line.unitPrice,
    quantity: line.quantity,
    totalPrice: line.totalPrice,
    teeth: line.teethNumbers ?? [],
    medicalAidCovered: line.medicalAidCovered,
    auto: line.isAutoGenerated === true,
    required: line.isRequired === true
  }));

const find = (code: string) => {
  const row = tariffs.find(item => item.code === code);
  if (!row) throw new Error(`no tariff ${code}`);
  return row;
};

// Business rule: a quote must hold exactly the lines its visit would invoice, so the quote builder adds a
// code the way the visit screens' "Add services" does (addServiceDirectly): the code at its tariff price,
// 8109 once per visit at the top, and the 8346 material line after a restorative procedure.
describe('addTariffLines builds the same lines as the visit screens', () => {
  it('matches addServiceDirectly for a filling: 8109 first, the procedure, then its 8346', () => {
    const lines = added(addTariffLines([], { code: '8367', quantity: 1, tooth: '16' }, context()));

    // What addServiceDirectly builds for the same pick (AddVisitTabs / EditVisitTabs)
    const procedure = buildTariffLine(find('8367'), 1, '16', true);
    if (!procedure.ok) throw new Error(procedure.message);
    const infectionControl = buildInfectionControlLine(tariffs, true, procedure.service.id);
    const material = buildMaterialFactorLine(tariffs, procedure.service, true);
    if (!infectionControl.ok || !material.ok) throw new Error('visit screen lines refused');

    expect(billed(lines)).toEqual(billed([infectionControl.service, procedure.service, material.service]));
    expect(lines.map(line => line.totalPrice)).toEqual([34.4, 448.7, 44.87]);
    expect(findInvoiceLineProblems(lines)).toEqual([]);
  });

  it('links the automatic lines to the code that brought them, so removing the procedure removes its 8346', () => {
    const lines = added(addTariffLines([], { code: '8367', quantity: 1, tooth: '26' }, context()));
    const procedure = lines.find(line => line.code === '8367');
    expect(lines.find(line => line.code === '8346')?.parentServiceId).toBe(procedure?.id);
    expect(lines.find(line => line.code === '8109')?.parentServiceId).toBe(procedure?.id);
  });

  it('adds 8109 only when the visit does not have it yet, because the fund pays it once per visit', () => {
    const first = added(addTariffLines([], { code: '8101', quantity: 1 }, context()));
    const second = added(addTariffLines(first, { code: '8159', quantity: 1 }, context()));
    expect(second.filter(line => line.code === '8109')).toHaveLength(1);
  });

  it('does not add 8109 for practices that do not bill it (medical tariff lists)', () => {
    const lines = added(addTariffLines([], { code: '8101', quantity: 1 }, context({ autoInfectionControl: false })));
    expect(lines.map(line => line.code)).toEqual(['8101']);
  });

  it('still adds the code when 8109 has no tariff, and says why 8109 is missing (as the visit screens do)', () => {
    const withoutInfectionControl = tariffs.filter(row => row.code !== '8109');
    const outcome = addTariffLines([], { code: '8101', quantity: 1 }, context({ tariffs: withoutInfectionControl }));
    expect(outcome.status).toBe('added');
    if (outcome.status !== 'added') return;
    expect(outcome.lines.map(line => line.code)).toEqual(['8101']);
    expect(outcome.problems).toEqual([{ code: '8109', message: expect.stringMatching(/8109 has no tariff in effect/) }]);
  });

  it('sends the line to the fund only for a medical aid patient', () => {
    expect(added(addTariffLines([], { code: '8101', quantity: 1 }, context({ hasMedicalAid: false }))).every(line => !line.medicalAidCovered)).toBe(true);
  });

  it('keeps a note on the line, because invoiceService saves it with the invoice line', () => {
    const lines = added(addTariffLines([], { code: '8101', quantity: 1, notes: 'Recall in 6 months' }, context()));
    expect(lines.find(line => line.code === '8101')?.notes).toBe('Recall in 6 months');
  });
});

// Business rule: a code charged once per visit (8109, 8110, 8145) must never be billed twice on one visit.
describe('per-visit codes', () => {
  it('skips 8145 when the visit already has it and leaves the existing line as it was', () => {
    const visit = added(addTariffLines([], { code: '8145', quantity: 2 }, context()));
    const outcome = addTariffLines(visit, { code: '8145', quantity: 1 }, context());
    expect(outcome).toEqual({ status: 'skipped', lines: visit, reason: expect.stringMatching(/8145 is charged once per visit/) });
    expect(outcome.lines.find(line => line.code === '8145')?.quantity).toBe(2);
  });
});

// Business rule: lines that cannot be priced from the tariff list are refused with a reason; nothing is
// ever billed at a guessed price or at N$ 0.00.
describe('refused lines', () => {
  it('refuses 8346 on its own: its price is 10% of a procedure, so it only comes with one', () => {
    expect(addTariffLines([], { code: '8346', quantity: 1 }, context())).toMatchObject({ status: 'refused', message: expect.stringMatching(/added automatically/) });
  });

  it('refuses a code that has no tariff in effect', () => {
    expect(addTariffLines([], { code: '9999', quantity: 1 }, context())).toMatchObject({
      status: 'refused',
      message: expect.stringMatching(/9999 has no tariff in effect/)
    });
  });

  it('refuses a tooth code without a tooth, because the claim must name the tooth', () => {
    expect(addTariffLines([], { code: '8201', quantity: 1 }, context())).toMatchObject({ status: 'refused', message: expect.stringMatching(/needs a tooth number/) });
    expect(added(addTariffLines([], { code: '8201', quantity: 1, tooth: '48' }, context())).find(line => line.code === '8201')?.teethNumbers).toEqual(['48']);
  });

  it('refuses quantity 2 on a code billed once per line instead of charging one unit', () => {
    expect(addTariffLines([], { code: '8110', quantity: 2 }, context())).toMatchObject({ status: 'refused' });
  });

  it('matches codes without case or outer spaces', () => {
    const custom = [tariff('A12', '10.00')];
    expect(addTariffLines([], { code: ' a12 ', quantity: 1 }, context({ tariffs: custom, autoInfectionControl: false })).status).toBe('added');
  });
});

// Business rule: removing a procedure takes its 8346 material line with it (the material was for that
// filling), while 8109 stays as long as anything else is billed on the visit.
describe('removeLine', () => {
  const visit = added(
    addTariffLines(added(addTariffLines([], { code: '8367', quantity: 1, tooth: '16' }, context())), { code: '8101', quantity: 1 }, context())
  );
  const id = (code: string) => visit.find(line => line.code === code)?.id ?? '';

  it('removes the procedure with its 8346 and keeps 8109 for the remaining exam', () => {
    const after = removeLine(visit, id('8367'));
    expect(after.map(line => line.code)).toEqual(['8109', '8101']);
    expect(after.find(line => line.code === '8109')?.parentServiceId).toBeUndefined();
  });

  it('does not remove the required 8109 on its own', () => {
    expect(removeLine(visit, id('8109'))).toEqual(visit);
  });

  it('removes 8109 with the last billed line, because infection control alone is not a treatment', () => {
    expect(removeLine(removeLine(visit, id('8367')), id('8101'))).toEqual([]);
  });
});

// Business rule: 8109 per clinical staff member and 8346 with restorations are NAMAF dental rules. A dental quote or
// bundle bills 8109 at the practice's staff count (as the visit screens do); other practice types bill neither.
describe('addTariffLines applies the dental rules only to dental practices', () => {
  it('adds 8109 at the practice staff count', () => {
    const lines = added(addTariffLines([], { code: '8101', quantity: 1 }, context({ infectionControlStaff: 2 })));
    expect(lines[0]).toMatchObject({ code: '8109', quantity: 2, totalPrice: 68.8, maxQuantity: 3 });
    expect(findInvoiceLineProblems(lines)).toEqual([]);
  });

  it('adds neither 8109 nor 8346 for a practice that is not dental', () => {
    const lines = added(addTariffLines([], { code: '8367', quantity: 1, tooth: '16' }, context({ autoInfectionControl: false })));
    expect(lines.map(line => line.code)).toEqual(['8367']);
  });
});
