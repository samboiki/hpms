const lines = [quoteLine(2, '8367', 448.7, ['16']), quoteLine(1, '8109', 34.4), quoteLine(3, '8346', 44.4, ['16'])];
const patient = { name: 'Maria Shikongo', phone: '081 000 0000', email: null };

beforeEach(() => {
  drawn.length = 0;
});

// Business rule: the printed estimate is what the patient (and their fund, for pre-authorisation) keeps:
// practice and patient details, every line with its tooth, the totals and the estimate's basis, dates day
// first, and a clear statement that it is an estimate with its validity.
describe('buildQuoteDocument', () => {
  const doc = buildQuoteDocument(quote, lines, letterhead, patient);

  it('lists the lines in quote order with teeth and amounts', () => {
    expect(doc.rows.map(row => [row.code, row.tooth, row.total, row.patient])).toEqual([
      ['8109', '', 'N$ 34.40', 'N$ 34.40'],
      ['8367', '16', 'N$ 448.70', 'N$ 448.70'],
      ['8346', '16', 'N$ 44.40', 'N$ 44.40']
    ]);
  });

  it('writes the dates day first and the totals of the estimate', () => {
    expect(doc).toMatchObject({ title: 'TREATMENT ESTIMATE', number: 'Q2026-0007', dateText: '07/10/2026', validUntilText: '05/01/2027' });
    expect(doc.totals).toEqual([
      { label: 'Total', value: 'N$ 527.50', bold: true },
      { label: 'Medical aid (estimated)', value: 'N$ 0.00' },
      { label: 'Patient portion (estimated)', value: 'N$ 527.50', bold: true }
    ]);
  });

  it('prints the estimate basis, pre-authorisation, fund reference, notes, validity and a signature line', () => {
    expect(doc.notes).toEqual([
      'The practice has no Namibia Medical Care rates on file for these codes.',
      'Pre-authorisation number: PA-889',
      'Fund reference: REF-1',
      'Notes: Two visits needed',
      expect.stringMatching(/estimate, not an invoice\. It is valid until 05\/01\/2027/),
      expect.stringMatching(/I accept this estimate/)
    ]);
  });

  it('shows the medical aid with the member number, or says the patient is private', () => {
    expect(doc.patientLines).toContain('Medical aid: Namibia Medical Care - Gold (member no NMC123)');
    const privateDoc = buildQuoteDocument({ ...quote, medicalAidName: null, medicalAidScheme: null, membershipNumber: null }, lines, letterhead, patient);
    expect(privateDoc.patientLines).toContain('Medical aid: none on file (private patient)');
  });

  it('uses the practice letterhead, and bank details only when they are complete', () => {
    expect(doc.practiceLines).toEqual(['12 Sam Nujoma Drive', 'Windhoek, Namibia 9000', 'Tel: 061 123 456', 'Email: hello@smile.na', 'Practice no: 0123456']);
    expect(doc.footerLeft).toEqual(['Licence: DEN-77', 'Tax no: 1234567-01-5']);
    expect(doc.footerRight).toEqual(['FNB Namibia', 'Acc: 62000000000', 'Branch: 280172']);
    expect(buildQuoteDocument(quote, lines, { ...letterhead, accountNumber: null }, patient).footerRight).toEqual([]);
    expect(doc.primaryColor).toBe('#30b4be');
    expect(buildQuoteDocument(quote, lines, { ...letterhead, primaryColor: null }, patient).primaryColor).toBe('#01b9d4');
    expect(doc.fileName).toBe('estimate-Q2026-0007.pdf');
  });
});

describe('renderQuotePdf', () => {
  it('draws the title, number and page count on every page when the lines run over', () => {
    const many = Array.from({ length: 60 }, (_, index) => quoteLine(index + 1, '8107', 135.4));
    const pdf = renderQuotePdf(buildQuoteDocument(quote, many, letterhead, patient));
    const pages = pdf.internal.getNumberOfPages();
    expect(pages).toBeGreaterThan(1);
    for (let page = 1; page <= pages; page += 1) {
      const texts = drawn.filter(item => item.page === page).map(item => item.text);
      expect(texts).toContain('TREATMENT ESTIMATE');
      expect(texts).toContain('No Q2026-0007');
      expect(texts).toContain(`Page ${page} of ${pages}`);
      expect(texts).toContain('Licence: DEN-77');
    }
    expect(drawn.filter(item => item.text === 'N$ 135.40').length).toBeGreaterThanOrEqual(60);
    expect(drawn.map(item => item.text)).toContain('Patient portion (estimated)');
  });

  it('gives the PDF as base64 for an email attachment', () => {
    expect(quotePdfBase64(renderQuotePdf(buildQuoteDocument(quote, lines, letterhead, patient)))).toBe('JVBERi0xLjM=');
  });
});

describe("the practice's message on quotes (parity D22)", () => {
  const settings = { message: 'Prices may change after 30 days.', printOn: { invoice: true, quote: true, statement: false }, leaveSettledOff: false };

  it('prints it before the signature line when the practice chose quotes, and not otherwise', () => {
    const notes = buildQuoteDocument(quote, lines, { ...letterhead, documentSettings: settings }, patient).notes;
    expect(notes).toContain('Prices may change after 30 days.');
    expect(notes.indexOf('Prices may change after 30 days.')).toBe(notes.length - 2);
    const without = buildQuoteDocument(quote, lines, { ...letterhead, documentSettings: { ...settings, printOn: { invoice: true, quote: false, statement: false } } }, patient).notes;
    expect(without).not.toContain('Prices may change after 30 days.');
    expect(buildQuoteDocument(quote, lines, letterhead, patient).notes).not.toContain('Prices may change after 30 days.');
  });
});

// Business rule: a tooth is a dental practice's word. A dental estimate names the tooth of each line; a GP's or
// specialist's estimate has no Tooth column (nothing dental leaks into other disciplines), and still every amount.
describe('the Tooth column on the printed estimate', () => {
  const texts = () => drawn.map(item => item.text);

  it("is printed for a dental practice, with each line's tooth", () => {
    const doc = buildQuoteDocument(quote, lines, { ...letterhead, practiceType: 'dental' }, patient);
    expect(doc.showTooth).toBe(true);
    renderQuotePdf(doc);
    expect(texts()).toContain('Tooth');
    expect(texts()).toContain('16');
  });

  // Owner, 14 Oct 2026: dental specialists work like dental; the laboratory has no teeth to name
  it("is printed for a dental specialist's practice and the practice typed dental_practice, not for the dental laboratory", () => {
    ['orthodontist', 'periodontist', 'dental_practice'].forEach(practiceType => {
      expect(buildQuoteDocument(quote, lines, { ...letterhead, practiceType }, patient).showTooth).toBe(true);
    });
    expect(buildQuoteDocument(quote, lines, { ...letterhead, practiceType: 'dental_technician' }, patient).showTooth).toBe(false);
  });

  it('is left out for a GP practice, and when the practice type is not known', () => {
    const doc = buildQuoteDocument(quote, lines, { ...letterhead, practiceType: 'general_practice' }, patient);
    expect(doc.showTooth).toBe(false);
    expect(buildQuoteDocument(quote, lines, letterhead, patient).showTooth).toBe(false);
    renderQuotePdf(doc);
    expect(texts()).not.toContain('Tooth');
    expect(texts()).not.toContain('16');
    expect(texts()).toEqual(expect.arrayContaining(['Code', 'Description', 'Qty', 'Unit price', 'Total', 'Medical aid', 'Patient', 'N$ 448.70']));
  });
});
