import { describe, it, expect, vi } from 'vitest';
import type { ServiceSelection } from '../../../types/billing';
import type { ChartEntry, PlanItem } from '../../../utils/dental/chart';
import { addTariffLines, type LineContext } from '../../quotes/billingLines';
import { dentalTariffs, tariff } from '../../quotes/__tests__/quoteTestTariffs';
import { addCodeForTeeth, addedMessage, codesForTeeth, listTeeth, plannedCodesFor, sortTeeth, teethOnLines } from '../toothBilling';

// The module shows toasts after an add; nothing here reaches the screen or the database
vi.mock('react-hot-toast', () => ({ toast: Object.assign(vi.fn(), { success: vi.fn(), error: vi.fn() }) }));

const tariffs = [
  ...dentalTariffs(),
  tariff('8340', '700.00', { description: 'Each additional canal - molars', requires_tooth_number: 'YES', can_be_multiplied: 'PROGRESSIVE' }),
  tariff('8411', '4950.00', { description: 'Porcelain veneered crown', requires_tooth_number: 'YES' })
];
const context: LineContext = { tariffs, hasMedicalAid: true, autoInfectionControl: true, infectionControlStaff: 2 };
const find = (code: string) => {
  const row = tariffs.find(item => item.code === code);
  if (!row) throw new Error(`no tariff ${code}`);
  return row;
};

// Lines are compared on what is billed (ids are random)
const billed = (lines: readonly ServiceSelection[]) =>
  lines.map(line => ({ code: line.code, teeth: line.teethNumbers ?? [], quantity: line.quantity, total: line.totalPrice, auto: line.isAutoGenerated === true }));

const added = (outcome: ReturnType<typeof addCodeForTeeth>) => {
  if (outcome.status !== 'added') throw new Error(`expected lines, got ${outcome.status}`);
  return outcome;
};

// Business rule: NAMAF pays a restoration per tooth, and the claim and the tooth chart read one tooth per line. Choosing
// several teeth on the chart must bill exactly what one pick per tooth would: a line per tooth, each restoration with
// its own 8346 material line, and 8109 infection control once for the visit.
describe('several teeth chosen on the chart', () => {
  it('gives one line per tooth, each restoration with its own 8346, and one 8109 for the visit', () => {
    const outcome = added(addCodeForTeeth([], find('8367'), ['37', '36'], 1, context));
    expect(outcome.teeth).toEqual(['36', '37']);
    expect(billed(outcome.lines)).toEqual([
      { code: '8109', teeth: [], quantity: 2, total: 68.8, auto: true },
      { code: '8367', teeth: ['36'], quantity: 1, total: 448.7, auto: false },
      { code: '8346', teeth: ['36'], quantity: 1, total: 44.87, auto: true },
      { code: '8367', teeth: ['37'], quantity: 1, total: 448.7, auto: false },
      { code: '8346', teeth: ['37'], quantity: 1, total: 44.87, auto: true }
    ]);
  });

  it('bills the same as picking each tooth on its own', () => {
    const one = addTariffLines([], { code: '8367', quantity: 1, tooth: '36' }, context);
    if (one.status !== 'added') throw new Error('refused');
    const two = addTariffLines(one.lines, { code: '8367', quantity: 1, tooth: '37' }, context);
    if (two.status !== 'added') throw new Error('refused');
    expect(billed(added(addCodeForTeeth([], find('8367'), ['36', '37'], 1, context)).lines)).toEqual(billed(two.lines));
  });

  it('puts the units on each tooth for a code billed per unit (two extra canals on each molar)', () => {
    const outcome = added(addCodeForTeeth([], find('8340'), ['46', '36'], 2, context));
    expect(billed(outcome.lines.filter(line => line.code === '8340'))).toEqual([
      { code: '8340', teeth: ['36'], quantity: 2, total: 1400, auto: false },
      { code: '8340', teeth: ['46'], quantity: 2, total: 1400, auto: false }
    ]);
    // The tariff's special quantity rule is said, as when one tooth is picked
    expect(outcome.warnings.some(warning => warning.includes('special quantity rule'))).toBe(true);
  });

  it('accepts milk teeth', () => {
    const outcome = added(addCodeForTeeth([], find('8201'), ['84', '54'], 1, context));
    expect(outcome.lines.filter(line => line.code === '8201').map(line => line.teethNumbers)).toEqual([['54'], ['84']]);
  });
});

// Business rule: a fund refuses a line for a tooth item without a tooth ("tooth number required"), so such a code can
// never reach the visit, its invoice or the claim without one.
describe('a code that needs a tooth', () => {
  it('is not added without a tooth, and the lines stay as they were', () => {
    const existing = added(addCodeForTeeth([], find('8101'), [], 1, context)).lines;
    const outcome = addCodeForTeeth(existing, find('8367'), [], 1, context);
    expect(outcome.status).toBe('refused');
    expect(outcome.lines).toEqual(existing);
    if (outcome.status === 'refused') expect(outcome.message).toContain('needs a tooth number');
  });

  it('is not added for something that is not a tooth', () => {
    expect(addCodeForTeeth([], find('8367'), ['19'], 1, context).status).toBe('refused');
  });

  it('adds nothing when the code cannot be priced for this patient: all teeth or none', () => {
    // The patient's fund lists two prices for the code: priceForPatient marks it, and nothing may guess between them
    const unclear = tariffs.map(row => (row.code === '8367' ? { ...row, price_problem: 'The fund has two prices for 8367 on this date.' } : row));
    const outcome = addCodeForTeeth([], find('8367'), ['36', '37'], 1, { ...context, tariffs: unclear });
    expect(outcome).toMatchObject({ status: 'refused', lines: [], message: 'The fund has two prices for 8367 on this date.' });
  });
});

// Business rule: a code that needs no tooth (an examination, a radiograph) is billed once for the visit, as before;
// the teeth chosen on the chart do not multiply it.
it('adds a code that needs no tooth once, without the chosen teeth', () => {
  const outcome = added(addCodeForTeeth([], find('8101'), ['36', '37'], 1, context));
  expect(billed(outcome.lines).filter(line => line.code === '8101')).toEqual([{ code: '8101', teeth: [], quantity: 1, total: 254.7, auto: false }]);
  expect(outcome.teeth).toEqual([]);
});

const planEntry = (id: string, tooth: string, code: string, status: ChartEntry['status'] = 'planned'): PlanItem => ({
  entry: {
    id,
    tooth,
    surfaces: null,
    work: 'filling',
    status,
    tariffCode: code,
    planVisit: 1,
    planOrder: 1,
    quoteId: null,
    visitId: null,
    invoiceId: null,
    note: null,
    recordedBy: null,
    recordedAt: '2026-10-01T09:00:00Z',
    statusChangedAt: null,
    voidedAt: null,
    voidedBy: null,
    voidReason: null
  },
  done: status === 'done',
  billedBy: null,
  doneDate: null,
  quote: null
});

// Business rule: at the desk the codes for the chosen teeth must be quick to find. Work planned on those teeth comes
// first (it is what the patient came for), then the practice's most used codes; tooth codes before the others. 8346
// is never offered (it comes with its restoration) and a once-per-visit code already on the visit is not offered again.
describe('the codes offered for the chosen teeth', () => {
  const usage = { '8101': 120, '8109': 300, '8367': 64, '8201': 38, '8346': 105 };

  it('lists tooth codes first: planned work on the chosen teeth, then the most used', () => {
    const planned = plannedCodesFor([planEntry('p1', '36', '8411'), planEntry('p2', '46', '8340')], new Set(['36']));
    const codes = codesForTeeth(tariffs, { usage, query: '', planned, teeth: ['36'], lines: [] });
    expect(codes.forTeeth.map(choice => choice.code)).toEqual(['8411', '8367', '8201', '8340']);
    expect(codes.forTeeth[0].plannedFor).toEqual(['36']);
    expect(codes.withoutTooth.map(choice => choice.code)).toEqual(['8109', '8101', '8104', '8107', '8110', '8131', '8145', '8159']);
  });

  it('never offers 8346, and not a once-per-visit code the visit already has', () => {
    const lines = added(addCodeForTeeth([], find('8367'), ['36'], 1, context)).lines;
    const codes = codesForTeeth(tariffs, { usage, query: '', planned: new Map(), teeth: ['36'], lines });
    const offered = [...codes.forTeeth, ...codes.withoutTooth].map(choice => choice.code);
    expect(offered).not.toContain('8346');
    expect(offered).not.toContain('8109');
    expect(codes.forTeeth.find(choice => choice.code === '8367')?.alreadyOn).toEqual(['36']);
  });

  it('puts the best match first while searching', () => {
    const codes = codesForTeeth(tariffs, { usage, query: '8201', planned: new Map(), teeth: ['36'], lines: [] });
    expect(codes.forTeeth.map(choice => choice.code)).toEqual(['8201']);
    expect(codes.withoutTooth).toEqual([]);
  });

  it('only counts open planned work on the chosen teeth', () => {
    const items = [planEntry('a', '36', '8367'), planEntry('b', '37', '8201'), planEntry('c', '36', '8411', 'done')];
    expect([...plannedCodesFor(items, new Set(['36'])).entries()]).toEqual([['8367', ['36']]]);
  });
});

describe('what the screen says', () => {
  it('names the teeth in FDI order and in plain words', () => {
    expect(sortTeeth(['47', '11', '84', '11', ' 36 '])).toEqual(['11', '36', '47', '84']);
    expect([listTeeth(['36']), listTeeth(['36', '37']), listTeeth(['36', '37', '46'])]).toEqual(['36', '36 and 37', '36, 37 and 46']);
  });

  it('says which teeth were billed and that each restoration has its material line', () => {
    const outcome = added(addCodeForTeeth([], find('8367'), ['36', '37'], 1, context));
    expect(addedMessage('8367', outcome.teeth, outcome.added)).toBe('Added 8367 for teeth 36 and 37, each with its 8346 material line.');
    expect(addedMessage('8101', [], [])).toBe('Added 8101.');
  });

  it('marks the teeth on the visit by their procedures, not by their 8346 lines', () => {
    const lines = added(addCodeForTeeth([], find('8367'), ['36', '37'], 1, context)).lines;
    expect([...teethOnLines(lines).entries()]).toEqual([
      ['36', ['8367']],
      ['37', ['8367']]
    ]);
  });
});

