const withFillings = [
  ...tariffs,
  tariff('8368', '560.00', { description: 'Resin - two surfaces, posterior', requires_tooth_number: 'YES' }),
  tariff('8369', '663.00', { description: 'Resin - three surfaces, posterior', requires_tooth_number: 'YES' }),
  tariff('8182', '832.80', { description: 'Root planing, per quadrant' }),
  tariff('8185', '1087.40', { description: 'Gingivectomy, per quadrant', requires_tooth_number: 'YES' })
];
const fillingContext: LineContext = { ...context, tariffs: withFillings };
const findIn = (code: string) => withFillings.find(item => item.code === code) as (typeof withFillings)[number];

// Business rule: the fund pays a filling by the code for its number of surfaces, and reads the tooth and surfaces from
// the claim ("TOOTH: 46 MO"). Surfaces tapped on the chart go with the filling's line; a code for another number of
// surfaces is refused at once, naming the code that fits, before it reaches the invoice.
describe('surfaces marked on the one chosen tooth', () => {
  it('go with the filling line, in the chart order; the 8346 keeps the tooth only', () => {
    const outcome = added(addCodeForTeeth([], findIn('8368'), ['46'], 1, fillingContext, { surfaces: 'om' }));
    const filling = outcome.lines.find(line => line.code === '8368');
    expect(filling).toMatchObject({ teethNumbers: ['46'], toothSurfaces: 'MO' });
    expect(outcome.lines.find(line => line.code === '8346')?.toothSurfaces).toBeUndefined();
  });

  it('refuse a code for another number of surfaces, naming the code that fits', () => {
    const outcome = addCodeForTeeth([], findIn('8369'), ['46'], 1, fillingContext, { surfaces: 'MO' });
    expect(outcome).toEqual({ status: 'refused', lines: [], message: '8369 is for 3 surfaces, but 2 are marked (M O). Use 8368, the code for 2 surfaces.' });
  });

  it('do not go with work that is not billed by surfaces, nor with several teeth', () => {
    expect(added(addCodeForTeeth([], findIn('8201'), ['46'], 1, fillingContext, { surfaces: 'MO' })).lines.find(line => line.code === '8201')?.toothSurfaces).toBeUndefined();
    const two = added(addCodeForTeeth([], findIn('8368'), ['46', '47'], 1, fillingContext, { surfaces: 'MO' }));
    expect(two.lines.filter(line => line.code === '8368').map(line => line.toothSurfaces)).toEqual([undefined, undefined]);
  });

  it('put the code for the surfaces marked first, and say which codes fit', () => {
    const codes = codesForTeeth(withFillings, { usage: {}, query: '', planned: new Map(), teeth: ['46'], lines: [], surfaces: 'MO' });
    expect(codes.forTeeth[0]).toMatchObject({ code: '8368', surfaceFit: 'fits' });
    expect(codes.forTeeth.find(choice => choice.code === '8369')?.surfaceFit).toBe('other');
    expect(codes.forTeeth.find(choice => choice.code === '8201')?.surfaceFit).toBeNull();
  });
});

// Business rule: root planing (8182) and gingivectomy (8185) are paid per quadrant. One line per tooth would bill the
// quadrant once per tooth, so the chart bills one line per quadrant of the chosen teeth, with its quadrant (and the
// quadrant's teeth when the fund wants teeth for the code).
describe('a code billed per quadrant', () => {
  it('gives one line per quadrant of the chosen teeth', () => {
    const outcome = added(addCodeForTeeth([], findIn('8182'), ['46', '47', '14'], 1, fillingContext));
    expect(outcome.quadrants).toEqual([1, 4]);
    expect(outcome.lines.filter(line => line.code === '8182').map(line => [line.toothQuadrant, line.teethNumbers])).toEqual([[1, undefined], [4, undefined]]);
    expect(addedMessage('8182', outcome.teeth, outcome.added, outcome.quadrants)).toBe('Added 8182 for the upper right and lower right quadrants.');
  });

  it("carries the quadrant's teeth when the code needs teeth", () => {
    const outcome = added(addCodeForTeeth([], findIn('8185'), ['46', '47'], 1, fillingContext));
    expect(outcome.lines.filter(line => line.code === '8185').map(line => [line.toothQuadrant, line.teethNumbers, line.description])).toEqual([
      [4, ['46', '47'], 'Gingivectomy, per quadrant (Teeth 46, 47)']
    ]);
  });

  it('needs a tooth chosen, and is offered in its own group', () => {
    expect(addCodeForTeeth([], findIn('8182'), [], 1, fillingContext)).toMatchObject({ status: 'refused', message: expect.stringMatching(/per quadrant: choose a tooth in each quadrant/) });
    const codes = codesForTeeth(withFillings, { usage: {}, query: '', planned: new Map(), teeth: ['46'], lines: [] });
    expect(codes.forQuadrants.map(choice => choice.code).sort()).toEqual(['8182', '8185']);
    expect([...codes.forTeeth, ...codes.withoutTooth].some(choice => ['8182', '8185'].includes(choice.code))).toBe(false);
  });
});
