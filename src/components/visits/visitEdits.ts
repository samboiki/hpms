/**
 * What changes a visit besides typing, for the visit screen's edit flag (FullScreenEditVisitModal: its X and its links
 * ask before anything unsaved is lost): a billing line (a service, a tooth line, a medicine billed from stock) or a
 * prescribed medicine added or removed, or a line's quantity or teeth changed, also when it is done only by clicking.
 * - What the visit opened with is the starting point: loading it is not an edit.
 * - Prices are not part of it: they follow the patient's fund, the practitioner's rate or a promotion by themselves.
 * - Lines the app adds by itself (8109 infection control when a dental visit's Billing tab opens, an 8346 material line)
 *   are not either: opening a tab is not an edit, and they come and go with the lines staff add.
 */
import { useEffect, useRef } from 'react';
import type { ServiceSelection } from '../../types/billing';
import type { PrescribedMedicine } from './medicineEdit';

type BillingLine = Pick<ServiceSelection, 'id' | 'code' | 'quantity' | 'teethNumbers' | 'isAutoGenerated'>;

/** The lines and medicines as staff change them, as one text: equal while nothing was added, removed or re-counted. */
export function visitLinesKey(services: readonly BillingLine[], medications: readonly PrescribedMedicine[]): string {
  const lines = services
    .filter(line => !line.isAutoGenerated)
    .map(line => [line.id, line.code, line.quantity, (line.teethNumbers ?? []).join(',')]);
  return JSON.stringify([lines, medications.map(medicine => String(medicine.id))]);
}

/**
 * Calls `onEdited` whenever the visit's lines or medicines differ from what it opened with (taken once `ready`, that is
 * once the visit is loaded).
 */
export function useLineEdits(params: {
  ready: boolean;
  services: readonly BillingLine[];
  medications: readonly PrescribedMedicine[];
  onEdited?: () => void;
}): void {
  const { ready, services, medications, onEdited } = params;
  const opened = useRef<string | null>(null);
  const key = visitLinesKey(services, medications);
  useEffect(() => {
    if (!ready) return;
    if (opened.current === null) {
      opened.current = key;
      return;
    }
    if (key !== opened.current) onEdited?.();
  }, [ready, key, onEdited]);
}
