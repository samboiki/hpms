/**
 * The details under a billing line on the visit's Billing tab (parity D1, D2): the ICD-10 codes the claim will carry,
 * a fee changed from the price list with its reason, and the narrative printed under the line.
 */
import React from 'react';
import { describe, expect, it, vi } from 'vitest';
import { fireEvent, render, screen } from '@testing-library/react';
import '@testing-library/jest-dom';
import BillingLineDetails from '../BillingLineDetails';
import type { ServiceSelection } from '../../../types/billing';

// The line helpers are pure; nothing here may reach the database
vi.mock('../../../lib/supabase', () => ({ supabase: {} }));

const consultation: ServiceSelection = {
  id: 'line-1', tariffId: 't-0190', code: '0190', description: 'Consultation', category: 'Consultation', unitPrice: 450, quantity: 1, totalPrice: 450
};

const renderLine = (props: Partial<React.ComponentProps<typeof BillingLineDetails>> = {}) => {
  const onChange = vi.fn();
  render(
    <BillingLineDetails
      service={consultation}
      visitDate="2026-10-09"
      visitPractitionerId={null}
      practitioners={[]}
      editable={false}
      hasMedicalAid
      amounts={null}
      today="2026-10-09"
      onChange={onChange}
      icd10={{ codes: ['J06.9'], suggested: true, sourceLabel: 'from the visit diagnosis' }}
      codesEditable
      canChangeFee
      {...props}
    />
  );
  return onChange;
};

describe('ICD-10 codes on a billing line', () => {
  // Staff must see which codes the claim will carry, and where suggested ones came from, before saving the invoice
  it('shows the codes the line will be claimed with and where suggested codes came from', () => {
    renderLine();
    expect(screen.getByText('ICD-10 J06.9 (from the visit diagnosis)')).toBeInTheDocument();
  });

  // No ICD-10, no payment: a medical aid line without a code is pointed out before the claim is stopped for it
  it('warns when a medical aid line has no code yet', () => {
    renderLine({ icd10: { codes: [], suggested: false, sourceLabel: null } });
    expect(screen.getByText('No ICD-10 code yet: the medical aid needs one')).toBeInTheDocument();
  });

  it('sends codes typed in the editor tidied, main code first', () => {
    const onChange = renderLine({ icd10: { codes: [], suggested: false, sourceLabel: null } });
    fireEvent.click(screen.getByRole('button', { name: 'Change' }));
    fireEvent.change(screen.getByLabelText(/ICD-10 code/), { target: { value: 'j069' } });
    expect(onChange).toHaveBeenLastCalledWith({ icd10Codes: ['J06.9'] });
  });
});

describe('a fee changed from the price list', () => {
  // The claim sends the charged fee, so a different fee must always say why
  it('is refused without a reason and sent with one', () => {
    const onChange = renderLine();
    fireEvent.click(screen.getByRole('button', { name: 'Change' }));
    fireEvent.change(screen.getByLabelText('New fee per unit in N$'), { target: { value: '400' } });
    fireEvent.click(screen.getByRole('button', { name: 'Use this fee' }));
    expect(screen.getByRole('alert')).toHaveTextContent(/Say why the fee is changed/);
    expect(onChange).not.toHaveBeenCalled();

    fireEvent.change(screen.getByLabelText('Reason'), { target: { value: 'Pensioner rate' } });
    fireEvent.click(screen.getByRole('button', { name: 'Use this fee' }));
    expect(onChange).toHaveBeenCalledWith({ fee: { unitPrice: 400, reason: 'Pensioner rate' } });
  });

  it('shows the fee it replaced and the reason, and can be put back', () => {
    const changed = { ...consultation, unitPrice: 400, totalPrice: 400, feeOverride: { reason: 'Pensioner rate', fromUnitPrice: 450, by: 'u1', at: '2026-10-09T08:00:00.000Z' } };
    const onChange = renderLine({ service: changed });
    expect(screen.getByText('Fee changed from N$ 450.00: Pensioner rate')).toBeInTheDocument();
    fireEvent.click(screen.getByRole('button', { name: 'Change' }));
    fireEvent.click(screen.getByRole('button', { name: 'Back to N$ 450.00' }));
    expect(onChange).toHaveBeenCalledWith({ fee: null });
  });

  // Invoice rights (invoiceRights.ts): only staff who may raise invoices may change what is charged
  it('is not offered to staff without billing rights', () => {
    renderLine({ canChangeFee: false });
    fireEvent.click(screen.getByRole('button', { name: 'Change' }));
    expect(screen.queryByRole('button', { name: 'Use this fee' })).toBeNull();
  });

  // 8109 and 8346 are priced by NAMAF's rule (per staff member, 10% of the restoration): their fee follows that rule
  it('is not offered on a line priced by a rule', () => {
    renderLine({ service: { ...consultation, code: '8346', isAutoGenerated: true } });
    fireEvent.click(screen.getByRole('button', { name: 'Change' }));
    expect(screen.queryByRole('button', { name: 'Use this fee' })).toBeNull();
  });
});

describe('the narrative printed under a line', () => {
  it('is saved when the field is left, and shown under the line', () => {
    const onChange = renderLine();
    fireEvent.click(screen.getByRole('button', { name: 'Change' }));
    const field = screen.getByLabelText('Note printed under this line');
    fireEvent.change(field, { target: { value: '  After-hours visit ' } });
    fireEvent.blur(field);
    expect(onChange).toHaveBeenCalledWith({ notes: 'After-hours visit' });
  });

  it('shows a saved narrative without opening the editor', () => {
    renderLine({ service: { ...consultation, notes: 'After-hours visit' } });
    expect(screen.getByText('After-hours visit')).toBeInTheDocument();
  });
});

// Parity D8 and D12: staff mark a line the patient pays all of (never claimed) and record the fund's authorisation
// number the claim line carries; both only for a medical aid patient, once the database keeps them
describe('who pays a line and its authorisation number', () => {
  it('lets staff mark a line the patient pays all of, and back to the fund rules', () => {
    const onChange = renderLine({ portionsEditable: true });
    fireEvent.click(screen.getByRole('button', { name: 'Change' }));
    const payer = screen.getByLabelText('Who pays this line');
    fireEvent.change(payer, { target: { value: 'patient' } });
    expect(onChange).toHaveBeenLastCalledWith({ paidBy: 'patient' });
    fireEvent.change(payer, { target: { value: 'split' } });
    expect(onChange).toHaveBeenLastCalledWith({ paidBy: null });
  });

  // A comma or a 22nd character would break the claim file, so it is refused on the line
  it('takes an authorisation number the claim can carry and refuses one it cannot', () => {
    const onChange = renderLine({ portionsEditable: true });
    fireEvent.click(screen.getByRole('button', { name: 'Change' }));
    const field = screen.getByLabelText(/Authorisation number/);
    fireEvent.change(field, { target: { value: '12,34' } });
    fireEvent.blur(field);
    expect(screen.getByRole('alert')).toHaveTextContent(/no spaces or commas/);
    expect(onChange).not.toHaveBeenCalledWith(expect.objectContaining({ authorisationNumber: expect.anything() }));
    fireEvent.change(field, { target: { value: ' PA-1234 ' } });
    fireEvent.blur(field);
    expect(onChange).toHaveBeenLastCalledWith({ authorisationNumber: 'PA-1234' });
  });

  it("shows a patient's own line and its authorisation number in plain words, and nothing to change for a private patient", () => {
    renderLine({ service: { ...consultation, paidBy: 'patient', authorisationNumber: 'PA-9' }, portionsEditable: true });
    expect(screen.getByText('Patient pays all (not claimed)')).toBeInTheDocument();
    expect(screen.getByText('Authorisation PA-9')).toBeInTheDocument();
  });

  it('offers no payer or authorisation for a private patient', () => {
    renderLine({ hasMedicalAid: false, portionsEditable: true });
    fireEvent.click(screen.getByRole('button', { name: 'Change' }));
    expect(screen.queryByLabelText('Who pays this line')).toBeNull();
  });
});

// Owner decision (13 Oct 2026): the practice gives no discounts on invoice lines, so the line editor has no discount
// field; a line saved with a discount before still shows it, because the invoice and statements count it
describe('discounts on a line', () => {
  it('offers no discount field, even for a private patient', () => {
    renderLine({ hasMedicalAid: false, editable: true });
    fireEvent.click(screen.getByRole('button', { name: 'Change' }));
    expect(screen.getByLabelText('Date of service')).toBeInTheDocument();
    expect(screen.queryByLabelText(/Discount/)).toBeNull();
  });

  it('still shows a discount saved on the line before', () => {
    renderLine({
      hasMedicalAid: false,
      service: { ...consultation, discountAmount: 50 },
      amounts: { unitCents: 45000, grossCents: 45000, discountCents: 5000, totalCents: 40000, fundCents: 0, patientCents: 40000 }
    });
    expect(screen.getByText('Discount N$ 50.00')).toBeInTheDocument();
  });
});

// Parity D5: a filling is billed by its number of surfaces; the line says which tooth and surfaces it is for, lets
// staff mark them when the chart did not, and names the code that fits when the code is for another number
describe('tooth surfaces on a billing line', () => {
  const filling: ServiceSelection = {
    id: 'line-2', tariffId: 't-8369', code: '8369', description: 'Resin - three surfaces, posterior', category: 'Dental Service',
    unitPrice: 663, quantity: 1, totalPrice: 663, teethNumbers: ['46'], toothSurfaces: 'MO'
  };

  it('shows the tooth and surfaces, and names the code that fits', () => {
    renderLine({ service: filling });
    expect(screen.getByText('Tooth 46, MO')).toBeInTheDocument();
    expect(screen.getByText('8369 is for 3 surfaces, but 2 are marked (M O). Use 8368, the code for 2 surfaces.')).toBeInTheDocument();
  });

  it('lets staff mark the surfaces once the database keeps them', () => {
    const onChange = renderLine({ service: { ...filling, toothSurfaces: undefined }, codesEditable: false, canChangeFee: false, teethEditable: true });
    fireEvent.click(screen.getByRole('button', { name: 'Change' }));
    fireEvent.click(screen.getByRole('button', { name: /^D: distal/ }));
    expect(onChange).toHaveBeenLastCalledWith({ toothSurfaces: 'D' });
  });

  it('offers no surfaces before the database keeps them, nor on a line of several teeth', () => {
    renderLine({ service: { ...filling, toothSurfaces: undefined }, codesEditable: false, canChangeFee: false, teethEditable: false });
    expect(screen.queryByRole('button', { name: 'Change' })).toBeNull();
  });
});

// Parity D31: the medical aid pays the practice number on the line; a partner's lines say they bill under their own
it("says when the line's practitioner bills under their own practice number", () => {
  renderLine({
    visitPractitionerId: 'partner-1',
    practitioners: [{ id: 'partner-1', label: 'Dr. B Partner', hpcnaNumber: 'DEN00002', warning: null, ownPracticeNumber: '0999888777666', ratePercent: 120 }]
  });
  expect(screen.getByText('Bills under practice no 0999888777666')).toBeInTheDocument();
});

// Parity D15/F18: a line covered by an authorisation on the patient file shows the number it will carry, without anyone
// typing it; staff can still type another or take it off for this line (the number stays editable)
describe('the number a line takes from the patient authorisations', () => {
  it('shows the number and where it came from, and takes it off on request', () => {
    const onChange = renderLine({ portionsEditable: true, authorisation: { number: 'AUTH-77', authorisationId: 'a1' } });
    expect(screen.getByText("Authorisation AUTH-77 (from the patient's authorisations)")).toBeInTheDocument();
    fireEvent.click(screen.getByRole('button', { name: 'Change' }));
    expect(screen.getByLabelText(/Authorisation number/)).toHaveAttribute('placeholder', "From the patient's authorisations: AUTH-77");
    fireEvent.click(screen.getByRole('button', { name: 'Not on this line' }));
    expect(onChange).toHaveBeenLastCalledWith({ authorisationNumber: '' });
  });

  it('shows a number typed on the line instead, and nothing for a line it was taken off', () => {
    renderLine({ service: { ...consultation, authorisationNumber: 'TYPED-1' }, authorisation: { number: 'AUTH-77', authorisationId: 'a1' } });
    expect(screen.getByText('Authorisation TYPED-1')).toBeInTheDocument();
    expect(screen.queryByText(/AUTH-77/)).toBeNull();
  });
});

// Parity D7: specialists name the assistant, the anaesthetist and, where it differs from the visit's, the referring
// practitioner of a line (picked from staff and from the patient's referrals)
describe('the people on a line', () => {
  const people = {
    editable: true,
    referrals: [{
      id: 'r1', patientId: 'p1', referringName: 'Dr Test Referrer', referringPracticeNumber: '0123456', referringHpcna: null, referralNumber: null,
      referralDate: '2026-10-01', validUntil: null, reason: null, letterPath: null, letterName: null, removedAt: null, createdAt: null
    }]
  };
  const practitioners = [{ id: 'u-2', label: 'Dr. A Assistant', hpcnaNumber: 'MP00002', warning: null }];

  it('picks them from staff and the referrals, and shows them under the line', () => {
    const onChange = renderLine({ people, practitioners, codesEditable: false, canChangeFee: false });
    fireEvent.click(screen.getByRole('button', { name: 'Change' }));
    fireEvent.change(screen.getByLabelText('Assistant'), { target: { value: 'u-2' } });
    expect(onChange).toHaveBeenLastCalledWith({ assistantId: 'u-2' });
    fireEvent.change(screen.getByLabelText('Referring practitioner'), { target: { value: 'r1' } });
    expect(onChange).toHaveBeenLastCalledWith({ referralId: 'r1' });
    fireEvent.change(screen.getByLabelText('Anaesthetist'), { target: { value: '' } });
    expect(onChange).toHaveBeenLastCalledWith({ anaesthetistId: null });
  });

  it('names them on the line', () => {
    renderLine({ people, practitioners, service: { ...consultation, assistantId: 'u-2', referralId: 'r1' } });
    expect(screen.getByText('Assistant Dr. A Assistant')).toBeInTheDocument();
    expect(screen.getByText('Referred by Dr Test Referrer')).toBeInTheDocument();
  });

  it('offers no people before the database keeps them', () => {
    renderLine({ people: { ...people, editable: false }, codesEditable: false, canChangeFee: false });
    expect(screen.queryByRole('button', { name: 'Change' })).toBeNull();
  });
});

