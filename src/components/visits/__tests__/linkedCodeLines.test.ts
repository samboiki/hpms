/**
 * Linked codes on a visit (parity D13): a code staff add brings the codes the practice linked to it, for every
 * discipline. What matters to a practice: the consumables of a procedure are never forgotten, never billed twice, and
 * staff can see and remove them before saving.
 */
import { describe, expect, it } from 'vitest';
import type { ServiceSelection } from '../../../types/billing';
import { NO_CODE_RULES, type CodeRules } from '../../../utils/billing/codeRules';
import { buildTariffLine } from '../visitBillingLines';
import { addLinkedLines, describeAddedLinks, type RuledVisitTariff } from '../linkedCodeLines';

const tariff = (code: string, overrides: Partial<RuledVisitTariff> = {}): RuledVisitTariff => ({
  id: `t-${code}`,
  code,
  description: `Service ${code}`,
  price: '100.00',
  can_be_multiplied: 'YES',
  requires_tooth_number: 'NO',
  is_active: true,
  ...overrides
});
const linking = (...links: Array<[string, number]>): CodeRules => ({ ...NO_CODE_RULES, linkedCodes: links.map(([code, quantity]) => ({ code, quantity })) });
const lineFor = (item: RuledVisitTariff, overrides: Partial<ServiceSelection> = {}): ServiceSelection => {
  const built = buildTariffLine(item, 1, '', false);
  if (!built.ok) throw new Error(built.message);
  return { ...built.service, ...overrides };
};
const GP = { hasMedicalAid: false, dental: false };

describe('a code staff add brings its linked codes', () => {
  // A GP's procedure brings its dressing: priced from the dressing's own tariff, right after the procedure
  it("adds each linked code after the code, priced from its own tariff, marked with the code it came with", () => {
    const tariffs = [tariff('0300', { code_rules: linking(['0201', 2]) }), tariff('0201', { price: '35.50' }), tariff('0190')];
    const consult = lineFor(tariffs[2]);
    const procedure = lineFor(tariffs[0]);
    const result = addLinkedLines([procedure, consult], new Set([procedure.id]), tariffs, GP);
    expect(result.services.map(line => line.code)).toEqual(['0300', '0201', '0190']);
    expect(result.services[1]).toMatchObject({ code: '0201', quantity: 2, unitPrice: 35.5, totalPrice: 71, parentServiceId: procedure.id, linkedFrom: '0300' });
    expect(result.added).toEqual([{ from: '0300', codes: ['0201 x2'] }]);
    expect(describeAddedLinks(result.added)).toBe('Also added: 0201 x2 with 0300. Remove any you do not need before saving.');
  });

  it('adds a code billed once per line as that many lines', () => {
    const tariffs = [tariff('0300', { code_rules: linking(['0201', 2]) }), tariff('0201', { can_be_multiplied: 'NO' })];
    const procedure = lineFor(tariffs[0]);
    const result = addLinkedLines([procedure], new Set([procedure.id]), tariffs, GP);
    expect(result.services.filter(line => line.code === '0201').map(line => line.quantity)).toEqual([1, 1]);
  });

  // Lines already on the visit, linked lines and the app's own lines (8109, 8346) bring nothing: no chains, no loops
  it("brings nothing for lines that were there already, for linked lines, or for the app's own lines", () => {
    const tariffs = [tariff('0300', { code_rules: linking(['0201', 1]) }), tariff('0201', { code_rules: linking(['0300', 1]) })];
    const old = lineFor(tariffs[0]);
    const linked = lineFor(tariffs[1], { linkedFrom: '0300' });
    const automatic = lineFor(tariffs[0], { isAutoGenerated: true });
    const result = addLinkedLines([old, linked, automatic], new Set([linked.id, automatic.id]), tariffs, GP);
    expect(result.added).toEqual([]);
    expect(result.services).toHaveLength(3);
  });

  // A bundle that has the procedure and its dressing must not bill the dressing twice
  it('does not add a code the same addition already has', () => {
    const tariffs = [tariff('0300', { code_rules: linking(['0201', 1]) }), tariff('0201')];
    const procedure = lineFor(tariffs[0]);
    const dressing = lineFor(tariffs[1]);
    const result = addLinkedLines([procedure, dressing], new Set([procedure.id, dressing.id]), tariffs, GP);
    expect(result.services.filter(line => line.code === '0201')).toHaveLength(1);
  });

  it('says when a linked code has no price for the visit date, and adds the rest', () => {
    const tariffs = [tariff('0300', { code_rules: linking(['0299', 1], ['0201', 1]) }), tariff('0201')];
    const procedure = lineFor(tariffs[0]);
    const result = addLinkedLines([procedure], new Set([procedure.id]), tariffs, GP);
    expect(result.problems).toEqual(["0300 brings 0299, but 0299 has no price for this visit's date, so it was not added."]);
    expect(result.services.map(line => line.code)).toEqual(['0300', '0201']);
  });

  // A medical aid line the patient pays all of is never claimed; its consumable must not reach the fund on its own
  it("makes the linked line the patient's when the patient pays all of the code's line", () => {
    const tariffs = [tariff('0300', { code_rules: linking(['0201', 1]) }), tariff('0201')];
    const procedure = { ...lineFor(tariffs[0]), paidBy: 'patient' as const };
    const result = addLinkedLines([procedure], new Set([procedure.id]), tariffs, { hasMedicalAid: true, dental: false });
    expect(result.services[1].paidBy).toBe('patient');
  });
});

describe('dental practices', () => {
  // Dental keeps working exactly as before: its built-in 8346 and 8109 are never added a second time by a link
  it('never adds 8346 or 8109 through a link', () => {
    const tariffs = [tariff('8341', { requires_tooth_number: 'YES', code_rules: linking(['8346', 1], ['8109', 1], ['8145', 1]) }), tariff('8346'), tariff('8109'), tariff('8145')];
    const built = buildTariffLine(tariffs[0], 1, '16', false);
    if (!built.ok) throw new Error(built.message);
    const result = addLinkedLines([built.service], new Set([built.service.id]), tariffs, { hasMedicalAid: false, dental: true });
    expect(result.services.map(line => line.code)).toEqual(['8341', '8145']);
  });

  it("gives a linked code that needs a tooth the line's one tooth, and refuses it without one", () => {
    const tariffs = [tariff('8341', { requires_tooth_number: 'YES', code_rules: linking(['8350', 1]) }), tariff('8350', { requires_tooth_number: 'YES' })];
    const withTooth = buildTariffLine(tariffs[0], 1, '16', false);
    if (!withTooth.ok) throw new Error(withTooth.message);
    const result = addLinkedLines([withTooth.service], new Set([withTooth.service.id]), tariffs, { hasMedicalAid: false, dental: true });
    expect(result.services[1].teethNumbers).toEqual(['16']);

    const noTooth = { ...withTooth.service, id: 'no-tooth', teethNumbers: undefined };
    const refused = addLinkedLines([noTooth], new Set(['no-tooth']), tariffs, { hasMedicalAid: false, dental: true });
    expect(refused.problems[0]).toMatch(/8350 needs a tooth/);
  });
});
