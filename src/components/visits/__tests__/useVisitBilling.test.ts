import { describe, expect, it, vi } from 'vitest';
import type { ServiceSelection } from '../../../types/billing';
import type { VisitTariff } from '../visitBillingLines';

// The hook module also loads the invoice context; nothing here may reach the database
vi.mock('../../../lib/supabase', () => ({ supabase: {} }));

import { toothSaveProblem } from '../useVisitBilling';

const tariff = (code: string, requiresTooth: 'YES' | 'NO'): VisitTariff => ({
  id: `t-${code}`, code, description: `Tariff ${code}`, price: '373.90', can_be_multiplied: 'NO', requires_tooth_number: requiresTooth
});
const line = (code: string, overrides: Partial<ServiceSelection> = {}): ServiceSelection => ({
  id: `line-${code}`, tariffId: `t-${code}`, code, description: `Service ${code}`, category: 'Dental Service', unitPrice: 373.9, quantity: 1, totalPrice: 373.9, ...overrides
});
const tariffs = [tariff('8341', 'YES'), tariff('8342', 'YES'), tariff('8101', 'NO'), tariff('8346', 'YES')];

// Business rule (dental practices): a fund rejects a claim line whose code needs a tooth but carries none ("tooth
// number required"). Lines saved before the tooth flags were corrected can still lack one, so the visit is not saved
// until each such line has its tooth; the message names the codes so staff know which lines to fix.
describe('a dental visit with a line that needs a tooth but has none', () => {
  it('is refused, naming the code', () => {
    expect(toothSaveProblem([line('8341'), line('8101')], tariffs, 'dental')).toBe('Choose the tooth for 8341 before saving.');
  });

  it('names every such code once', () => {
    const lines = [line('8341'), line('8342', { id: 'a' }), line('8342', { id: 'b' })];
    expect(toothSaveProblem(lines, tariffs, 'dental')).toBe('Choose the tooth for 8341 and 8342 before saving.');
  });

  it('is saved once the line has its tooth; an automatic 8346 line follows its restoration and is not asked', () => {
    const lines = [line('8341', { teethNumbers: ['36'] }), line('8346', { isAutoGenerated: true, parentServiceId: 'line-8341' })];
    expect(toothSaveProblem(lines, tariffs, 'dental')).toBeNull();
  });

  // GPs and specialists bill no teeth: the NAMAF dental flags never stop their visits
  it('never stops a GP or specialist practice', () => {
    expect(toothSaveProblem([line('8341')], tariffs, 'general_practice')).toBeNull();
    expect(toothSaveProblem([line('8341')], tariffs, null)).toBeNull();
  });
});
