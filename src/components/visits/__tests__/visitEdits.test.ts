/**
 * What counts as changing a visit besides typing (visitEdits.ts), so the visit screen asks before losing it: a billing
 * line or a medicine added or removed by clicking only would otherwise be thrown away without a word. What matters to
 * a practice: no such change is lost silently, and nothing the app does by itself (loading the visit, the fund's
 * prices arriving, 8109 added when a dental Billing tab opens) makes staff answer a question about changes they never
 * made.
 */
import { describe, expect, it, vi } from 'vitest';
import { renderHook } from '@testing-library/react';
import { useLineEdits, visitLinesKey } from '../visitEdits';

const consultation = { id: 'line-1', code: '0190', quantity: 1, totalPrice: 520 };
const extraction = { id: 'line-2', code: '8201', quantity: 1, teethNumbers: ['46'], totalPrice: 208.2 };
const infectionControl = { id: 'line-3', code: '8109', quantity: 1, isAutoGenerated: true, totalPrice: 34.4 };
const amoxicillin = { id: 'med-1', medication_name: 'Amoxicillin' };
// The same line at another price (the fund's price arrived, or the practitioner's rate applies)
const atPrice = <T extends object>(line: T, totalPrice: number) => ({ ...line, totalPrice });

describe('visitLinesKey', () => {
  const opened = visitLinesKey([consultation, extraction], [amoxicillin]);

  it('changes when a line or a medicine is added or removed, or a line is re-counted or moved to another tooth', () => {
    expect(visitLinesKey([consultation], [amoxicillin])).not.toBe(opened);
    expect(visitLinesKey([consultation, extraction, { id: 'line-9', code: '8107', quantity: 1 }], [amoxicillin])).not.toBe(opened);
    expect(visitLinesKey([consultation, extraction], [])).not.toBe(opened);
    expect(visitLinesKey([consultation, extraction], [amoxicillin, { id: 1760000000000 }])).not.toBe(opened);
    expect(visitLinesKey([{ ...consultation, quantity: 2 }, extraction], [amoxicillin])).not.toBe(opened);
    expect(visitLinesKey([consultation, { ...extraction, teethNumbers: ['47'] }], [amoxicillin])).not.toBe(opened);
  });

  // The fund's prices, the practitioner's rate or a promotion change prices by themselves
  it('stays the same when only prices change', () => {
    expect(visitLinesKey([atPrice(consultation, 480), atPrice(extraction, 190)], [amoxicillin])).toBe(opened);
  });

  // Opening a dental visit's Billing tab adds 8109 by itself: looking at a tab is not a change
  it('leaves out the lines the app adds by itself', () => {
    expect(visitLinesKey([infectionControl, consultation, extraction], [amoxicillin])).toBe(opened);
  });
});

describe('useLineEdits', () => {
  type Props = Parameters<typeof useLineEdits>[0];

  it('starts from what the visit opened with: loading it is not a change', () => {
    const onEdited = vi.fn();
    const { rerender } = renderHook<void, Props>(props => useLineEdits(props), {
      initialProps: { ready: false, services: [], medications: [], onEdited }
    });
    // The visit's own lines and medicines arrive as it finishes loading
    rerender({ ready: true, services: [consultation, extraction], medications: [amoxicillin], onEdited });
    // 8109 added when the Billing tab opens, and the fund's prices arriving
    rerender({ ready: true, services: [infectionControl, atPrice(consultation, 480), extraction], medications: [amoxicillin], onEdited });
    expect(onEdited).not.toHaveBeenCalled();
  });

  it('reports a line added by clicking only, and a medicine removed by clicking only', () => {
    const onEdited = vi.fn();
    const { rerender } = renderHook<void, Props>(props => useLineEdits(props), {
      initialProps: { ready: true, services: [consultation], medications: [amoxicillin], onEdited }
    });
    rerender({ ready: true, services: [consultation, extraction], medications: [amoxicillin], onEdited });
    expect(onEdited).toHaveBeenCalledTimes(1);

    const second = vi.fn();
    const removed = renderHook<void, Props>(props => useLineEdits(props), {
      initialProps: { ready: true, services: [consultation], medications: [amoxicillin], onEdited: second }
    });
    removed.rerender({ ready: true, services: [consultation], medications: [], onEdited: second });
    expect(second).toHaveBeenCalledTimes(1);
  });
});
