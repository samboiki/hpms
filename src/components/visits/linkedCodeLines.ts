/**
 * Linked codes on a visit (parity D13), for every discipline: when staff add a code that brings other codes (the
 * practice's rules, codeRules.ts), those codes are added right after it, each priced from its own tariff for this
 * patient (the fund's price, the practitioner's rate) by buildTariffLine, as if staff had added them. Staff see them
 * before saving ("Added with ...") and can remove any; removing the code removes them too (parentServiceId).
 * - Only a code staff add brings its linked codes: a linked code never brings its own (no chains, no loops), and lines
 *   the app adds by itself (8109, 8346) bring none.
 * - A code the same addition already has (a bundle with both codes) is not added twice.
 * - A code billed once per line comes as that many lines; a code that needs a tooth takes the line's one tooth.
 * - A linked line of a line the patient pays all of (never claimed) is the patient's too.
 * - Dental practices keep their built-in 8346 and 8109 exactly as before; those two are never linked again.
 */
import type { ServiceSelection } from '../../types/billing';
import { codeKey, describeLinkedCode, type CodeRules } from '../../utils/billing/codeRules';
import { normalizeMultiplyRule } from '../../utils/billing/pricing';
import { INFECTION_CONTROL_CODE, MATERIAL_FACTOR_CODE } from '../../utils/billing/tariffRules';
import { buildTariffLine, type VisitTariff } from './visitBillingLines';

/** A billable tariff with its code's rules (practiceTariffService.loadPracticeTariffRows attaches them) */
export type RuledVisitTariff = VisitTariff & { code_rules?: CodeRules | null };

export interface LinkedLinesResult {
  services: ServiceSelection[];
  /** The codes that brought lines, with what they brought ("0201", "0202 x2") */
  added: Array<{ from: string; codes: string[] }>;
  /** Linked codes that could not be added, in plain words */
  problems: string[];
}

const DENTAL_AUTOMATIC_CODES: readonly string[] = [MATERIAL_FACTOR_CODE, INFECTION_CONTROL_CODE];

/**
 * The lines with the linked codes of the newly added lines (`freshIds`) put in after each of them. The billable
 * tariffs are the visit's (in effect on the visit date and priced for the patient): a linked code without one is not
 * added, and the problem says so.
 */
export function addLinkedLines(
  services: readonly ServiceSelection[],
  freshIds: ReadonlySet<string>,
  tariffs: readonly RuledVisitTariff[],
  options: { hasMedicalAid: boolean; dental: boolean }
): LinkedLinesResult {
  const byCode = new Map<string, RuledVisitTariff>();
  tariffs.forEach(tariff => {
    if (!byCode.has(codeKey(tariff.code))) byCode.set(codeKey(tariff.code), tariff);
  });
  const fresh = services.filter(service => freshIds.has(service.id));
  // What this addition brings by itself (a bundle may have the linked code already)
  const addedCodes = new Set(fresh.filter(service => !service.linkedFrom).map(service => codeKey(service.code)));
  let result = [...services];
  const added: LinkedLinesResult['added'] = [];
  const problems: string[] = [];

  fresh.forEach(parent => {
    if (parent.isAutoGenerated || parent.linkedFrom) return;
    const parentCode = codeKey(parent.code);
    const links = byCode.get(parentCode)?.code_rules?.linkedCodes ?? [];
    if (links.length === 0) return;
    const lines: ServiceSelection[] = [];
    const codes: string[] = [];
    links.forEach(link => {
      if (addedCodes.has(link.code)) return;
      if (options.dental && DENTAL_AUTOMATIC_CODES.includes(link.code)) return;
      const tariff = byCode.get(link.code);
      if (!tariff) {
        problems.push(`${parentCode} brings ${link.code}, but ${link.code} has no price for this visit's date, so it was not added.`);
        return;
      }
      const teeth = (parent.teethNumbers ?? []).filter(tooth => tooth.trim());
      const needsTooth = tariff.requires_tooth_number === 'YES';
      if (needsTooth && teeth.length !== 1) {
        problems.push(`${link.code} needs a tooth, so it was not added with ${parentCode}. Add it from the chart.`);
        return;
      }
      const tooth = needsTooth ? teeth[0] : '';
      // A code billed once per line comes as that many lines; one billed per unit as one line of that quantity
      const perLine = normalizeMultiplyRule(tariff.can_be_multiplied) === 'NO' && !tariff.max_quantity;
      const outcomes = perLine
        ? Array.from({ length: link.quantity }, () => buildTariffLine(tariff, 1, tooth, options.hasMedicalAid))
        : [buildTariffLine(tariff, link.quantity, tooth, options.hasMedicalAid)];
      const refused = outcomes.find(outcome => !outcome.ok);
      if (refused && !refused.ok) {
        problems.push(`${link.code} was not added with ${parentCode}: ${refused.message}`);
        return;
      }
      outcomes.forEach(outcome => {
        if (!outcome.ok) return;
        lines.push({
          ...outcome.service,
          parentServiceId: parent.id,
          linkedFrom: parentCode,
          // Never claimed on its own when the patient pays all of the line it came with
          ...(options.hasMedicalAid && parent.paidBy === 'patient' ? { paidBy: 'patient' as const } : {})
        });
      });
      codes.push(describeLinkedCode(link));
    });
    if (lines.length === 0) return;
    // Right after the code and the lines that already belong to it (its 8346 material line)
    const index = result.findIndex(service => service.id === parent.id);
    let end = index;
    while (end + 1 < result.length && result[end + 1].parentServiceId === parent.id) end += 1;
    result = [...result.slice(0, end + 1), ...lines, ...result.slice(end + 1)];
    added.push({ from: parentCode, codes });
  });

  return { services: result, added, problems };
}

/** What came with what: "0201 x2 with 0300; 0202 with 0400" */
export const linkedCodesText = (added: LinkedLinesResult['added']): string =>
  added.map(item => `${item.codes.join(', ')} with ${item.from}`).join('; ');

/** The toast after linked codes were added: what came with what, and that staff can remove any */
export function describeAddedLinks(added: LinkedLinesResult['added']): string {
  return `Also added: ${linkedCodesText(added)}. Remove any you do not need before saving.`;
}
