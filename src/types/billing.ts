// Billing Types for HPMS System
// Integrates with dental practice codes and medical aid processing
import type { LineFeeOverride } from '../utils/billing/invoiceLineRow';
import type { PaidBy } from '../utils/billing/lineSplit';

export interface ServiceSelection {
  id: string;
  tariffId: string;
  code: string;
  description: string;
  category: string;
  subcategory?: string;
  unitPrice: number;
  quantity: number;
  totalPrice: number;
  notes?: string;
  requiresPreAuth?: boolean;
  medicalAidCovered?: boolean;
  coveragePercentage?: number;
  businessRule?: string;
  exampleCalculation?: string;
  requiresTeethNumbers?: boolean;
  canBeMultiplied?: boolean;
  teethNumbers?: string[];
  isAutoGenerated?: boolean;
  parentServiceId?: string;
  /** The code that brought this line with it (the practice's linked codes, codeRules.ts); shown, never saved */
  linkedFrom?: string;
  isRequired?: boolean;
  isPriceProtected?: boolean;
  /** Highest quantity the line allows (8109: one per clinical staff member, at most 3); no limit beyond the tariff rule when absent */
  maxQuantity?: number;
  /** Date the service was given (yyyy-MM-dd); the visit date when absent. Claims use it per line. */
  serviceDate?: string;
  /** users.id of the practitioner who gave the service; the invoice's treating practitioner when absent */
  practitionerId?: string;
  /** N$ taken off the line (private patients only); totalPrice stays unit price x quantity */
  discountAmount?: number;
  /** The line's ICD-10 codes, main code first (at most 5, what the claim carries); absent: the suggested codes apply */
  icd10Codes?: string[];
  /** Set when the unit price was changed from the price list: why, the price before, who and when */
  feeOverride?: LineFeeOverride;
  /** Paid by one side only (medical aid patients): 'patient' lines are never claimed; absent: the fund's co-payment and levy */
  paidBy?: PaidBy;
  /** The fund's authorisation number for the line (claim field 31) */
  authorisationNumber?: string;
  /** Surfaces of the line's one tooth in the chart's order ("MO"; src/utils/dental/lineTeeth.ts); dental practices */
  toothSurfaces?: string;
  /** The quadrant of a code billed per quadrant: 1 upper right, 2 upper left, 3 lower left, 4 lower right */
  toothQuadrant?: number;
  /** users.id of the assistant on this line (theatre cases) */
  assistantId?: string;
  /** users.id of the anaesthetist on this line */
  anaesthetistId?: string;
  /** The line's own referral from the patient's register (claim fields 25, 43, 44); absent: the visit's */
  referralId?: string;
  /** The promotion its discount came from (private patients; src/utils/billing/promotions.ts) */
  promotionId?: string;
  /** The prepaid package it was paid from: billed at N$ 0.00, one session per unit (src/utils/billing/packages.ts) */
  packageId?: string;
}

export interface TariffCode {
  id: string;
  code: string;
  description: string;
  category: string;
  subcategory?: string;
  price: number;
  practiceType: string;
  unit: 'per_visit' | 'per_tooth' | 'per_treatment' | 'per_film' | 'per_surface';
  complexity: 'simple' | 'moderate' | 'complex';
  requiresPreAuth: boolean;
  medicalAidCode?: string;
  notes?: string;
  isActive: boolean;
  effectiveFrom: string;
  effectiveTo?: string;
}

export interface Invoice {
  id: string;
  invoiceNumber: string;
  patientId: string;
  visitId: string;
  practiceId: string;
  issueDate: string;
  dueDate: string;
  subtotal: number;
  tax: number;
  total: number;
  paymentStatus: 'pending' | 'partial' | 'paid' | 'overdue' | 'cancelled';
  paymentMethod?: 'cash' | 'card' | 'eft' | 'medical_aid' | 'mixed';
  medicalAidClaimNumber?: string;
  medicalAidStatus?: 'not_submitted' | 'submitted' | 'approved' | 'rejected' | 'partial';
  medicalAidAmount?: number;
  patientAmount?: number;
  notes?: string;
  createdAt: string;
  updatedAt: string;
  /** The treating practitioner (users.id) */
  practitionerId?: string | null;
  /** Things staff should know after saving (for example a co-payment the database did not keep) */
  warnings?: string[];
}

