  /**
   * Record ward round
   */
  static async recordWardRound(data: {
    admission_id: string;
    patient_id: string;
    doctor_id: string;
    round_type?: 'regular' | 'emergency' | 'discharge' | 'consultation';
    patient_condition: 'stable' | 'improving' | 'unchanged' | 'deteriorating' | 'critical';
    examination_findings?: string;
    treatment_changes?: string;
    new_orders?: string[];
    doctor_notes?: string;
    next_review_date?: string;
  }): Promise<{ success: boolean; error: Error | null }> {
    try {
      const { error } = await supabase
        .from('ward_rounds')
        .insert([{
          ...data,
          round_datetime: new Date().toISOString(),
        }]);

      if (error) throw error;

      // Update admission with latest condition
      await supabase
        .from('patient_admissions')
        .update({
          patient_condition: data.patient_condition,
          updated_at: new Date().toISOString(),
        })
        .eq('id', data.admission_id);

      return { success: true, error: null };
    } catch (error) {
      console.error('Error recording ward round:', error);
      return { success: false, error: error as Error };
    }
  }

