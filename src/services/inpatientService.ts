  // =============== REAL-TIME SUBSCRIPTIONS ===============

  /**
   * Subscribe to bed status changes
   */
  static subscribeToBedStatus(
    practiceId: string,
    callback: (payload: any) => void
  ) {
    return supabase
      .channel('bed-status-changes')
      .on(
        'postgres_changes',
        {
          event: '*',
          schema: 'public',
          table: 'beds',
          filter: `ward_id=in.(SELECT id FROM wards WHERE practice_id=eq.${practiceId})`,
        },
        callback
      )
      .subscribe();
  }

  /**
   * Subscribe to new admissions
   */
  static subscribeToAdmissions(
    practiceId: string,
    callback: (payload: any) => void
  ) {
    return supabase
      .channel('admission-changes')
      .on(
        'postgres_changes',
        {
          event: '*',
          schema: 'public',
          table: 'patient_admissions',
          filter: `practice_id=eq.${practiceId}`,
        },
        callback
      )
      .subscribe();
  }
