/**
 * Prices a planned visit exactly as its quote and its invoice will be priced: each item is added with the quotes' and
 * visit screens' line builder (addTariffLines in src/components/quotes/billingLines.ts, reused, not copied), so the
 * tariff in effect, the patient's fund price, 8109 infection control once per visit and the 8346 material line after
 * each restoration all come from the same code. The practice's linked codes come with each item, as when staff add its
 * code to a quote by hand (withLinkedCodes in src/components/quotes/quoteLinkedCodes.ts) or to the visit. A plan visit's
 * total is therefore its quote's total, to the cent.
 */
import type { ServiceSelection } from '../../types/billing';
import { addTariffLines, type LineContext } from '../../components/quotes/billingLines';
import { withLinkedCodes } from '../../components/quotes/quoteLinkedCodes';
import type { LinkedLinesResult } from '../../components/visits/linkedCodeLines';
import { sumCents, toCents } from '../billing/money';
import { INFECTION_CONTROL_CODE } from '../billing/tariffRules';
import type { PlanItem } from './chart';
import { formatSurfaces } from './surfaces';

export interface PricedItem {
  itemId: string;
  /** The item's lines: its code, the 8346 material line of a restoration and the codes the practice linked to its code */
  lineIds: string[];
  totalCents: number;
  /** Why the item could not be priced (it is left out of the total and its quote) */
  problem: string | null;
  /** Price notes from the line builder (the fund has no price for the code, a quantity rule ...) */
  warnings: string[];
}

export interface PricedVisit {
  visit: number;
  /** In quote order: 8109 first (added with the first item), then each item and its 8346 */
  lines: ServiceSelection[];
  items: ReadonlyMap<string, PricedItem>;
  /** Lines that belong to the visit rather than an item (8109 infection control) */
  visitLineIds: string[];
  /** Problems with the visit's automatic lines (8109 not in the tariff list) */
  visitProblems: string[];
  /** The practice's linked codes that came with the items ("0201 x2" with "8201"), to tell staff what the quote holds */
  linked: LinkedLinesResult['added'];
  totalCents: number;
}

/** What the line request says about the surfaces, so they travel with the line to the quote and the invoice. */
export const surfacesNote = (surfaces: string | null): string | null => (surfaces ? `Surfaces ${formatSurfaces(surfaces)}` : null);

const centsOf = (lines: readonly ServiceSelection[]): number =>
  sumCents(lines.map(line => (Number.isFinite(line.totalPrice) ? toCents(line.totalPrice) : 0)));

/** Prices one planned visit's items, in order (see the file comment). */
export function priceVisit(visit: number, items: readonly PlanItem[], context: LineContext): PricedVisit {
  let lines: ServiceSelection[] = [];
  const priced = new Map<string, PricedItem>();
  const visitLineIds: string[] = [];
  const visitProblems: string[] = [];
  const linked: LinkedLinesResult['added'] = [];

  for (const item of items) {
    const { entry } = item;
    const outcome = addTariffLines(
      lines,
      { code: entry.tariffCode ?? '', quantity: 1, tooth: entry.tooth, notes: surfacesNote(entry.surfaces) },
      context
    );
    if (outcome.status !== 'added') {
      priced.set(entry.id, {
        itemId: entry.id,
        lineIds: [],
        totalCents: 0,
        problem: outcome.status === 'refused' ? outcome.message : outcome.reason,
        warnings: []
      });
      continue;
    }
    // The codes the practice linked to the item's code come right after it, priced for this patient
    const withLinks = withLinkedCodes(lines, outcome.lines, context.tariffs, { hasMedicalAid: context.hasMedicalAid, dental: context.autoInfectionControl });
    const builderLineIds = new Set(outcome.lines.map(line => line.id));
    const linkedLines = withLinks.services.filter(line => !builderLineIds.has(line.id));
    lines = withLinks.services;
    linked.push(...withLinks.added);
    const built = outcome.added.filter(line => !(line.code === INFECTION_CONTROL_CODE && line.isAutoGenerated));
    outcome.added.filter(line => !built.includes(line)).forEach(line => visitLineIds.push(line.id));
    const own = [...built, ...linkedLines];
    // A linked code without a price is left out and said on the item, as the 8346 line is
    const warnings = [...outcome.warnings, ...withLinks.problems];
    outcome.problems.forEach(problem => {
      if (problem.code === INFECTION_CONTROL_CODE) visitProblems.push(problem.message);
      else warnings.push(problem.message);
    });
    priced.set(entry.id, { itemId: entry.id, lineIds: own.map(line => line.id), totalCents: centsOf(own), problem: null, warnings });
  }

  return { visit, lines, items: priced, visitLineIds, visitProblems: [...new Set(visitProblems)], linked, totalCents: centsOf(lines) };
}
