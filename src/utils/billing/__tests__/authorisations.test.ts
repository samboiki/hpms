import { describe, it, expect } from 'vitest';
import {
  authorisationNotices,
  authorisationState,
  authorisationUsageFrom,
  describeAuthorisation,
  draftFromQuote,
  emptyAuthorisationDraft,
  parseCodeList,
  suggestLineAuthorisations,
  validateAuthorisationDraft,
  type AuthorisationContext,
  type AuthorisationLine,
  type PatientAuthorisation
} from '../authorisations';

// Invented numbers only
const auth = (over: Partial<PatientAuthorisation> = {}): PatientAuthorisation => ({
  id: 'a1',
  patientId: 'p1',
  fundReference: 'MAG1',
  number: 'AUTH-100',
  validFrom: '2026-10-01',
  validTo: '2026-12-31',
  allCodes: false,
  codes: ['0190', '0191'],
  visitsAllowed: null,
  note: null,
  quoteId: null,
  removedAt: null,
  createdAt: '2026-10-01T08:00:00Z',
  ...over
});

const context = (over: Partial<AuthorisationContext> = {}): AuthorisationContext => ({
  authorisations: [auth()],
  usage: new Map(),
  fundReference: 'MAG1',
  visitDate: '2026-10-12',
  visitKey: 'visit-now',
  ...over
});

const line = (over: Partial<AuthorisationLine> = {}): AuthorisationLine => ({ id: 'l1', code: '0190', ...over });

// Business rule: a fund pays an authorised service only when the claim line carries the authorisation number (claim
// field 31). Reception records the authorisation once; every line it covers then carries the number without typing.
describe('lines take the number from the register', () => {
  it('when the fund, the date and the code match', () => {
    expect(suggestLineAuthorisations([line()], context()).get('l1')).toEqual({ number: 'AUTH-100', authorisationId: 'a1' });
  });

  it('not for a code it does not cover, another fund, a private patient or a line the patient pays all of', () => {
    expect(suggestLineAuthorisations([line({ code: '0201' })], context()).size).toBe(0);
    expect(suggestLineAuthorisations([line()], context({ fundReference: 'NMC1' })).size).toBe(0);
    expect(suggestLineAuthorisations([line()], context({ fundReference: null })).size).toBe(0);
    expect(suggestLineAuthorisations([line({ paidBy: 'patient' })], context()).size).toBe(0);
  });

  it('not outside its window: the line date counts, else the visit date', () => {
    expect(suggestLineAuthorisations([line({ serviceDate: '2027-01-01' })], context()).size).toBe(0);
    expect(suggestLineAuthorisations([line()], context({ visitDate: '2026-09-30' })).size).toBe(0);
    expect(suggestLineAuthorisations([line({ serviceDate: '2026-12-31' })], context({ visitDate: '2027-02-01' })).size).toBe(1);
  });

  // Business rule: the number is editable. A number staff typed, or took off, is what they decided.
  it('never over a number typed on the line, or one taken off', () => {
    expect(suggestLineAuthorisations([line({ authorisationNumber: 'OTHER' })], context()).size).toBe(0);
    expect(suggestLineAuthorisations([line({ authorisationNumber: '' })], context()).size).toBe(0);
  });

  it('prefers an authorisation that lists the code over one for all codes, then the newest', () => {
    const list = [auth({ id: 'all', number: 'ALL-1', allCodes: true, codes: [] }), auth({ id: 'listed', number: 'LISTED-1' }), auth({ id: 'newer', number: 'NEWER-1', validFrom: '2026-10-05' })];
    expect(suggestLineAuthorisations([line()], context({ authorisations: list })).get('l1')?.number).toBe('NEWER-1');
    expect(suggestLineAuthorisations([line({ code: '8101' })], context({ authorisations: list })).get('l1')?.number).toBe('ALL-1');
  });

  it("gives a material line (8346) its procedure's number", () => {
    const lines = [line({ id: 'proc', code: '0190' }), line({ id: 'mat', code: '8346', isAutoGenerated: true, parentServiceId: 'proc' })];
    expect(suggestLineAuthorisations(lines, context()).get('mat')?.number).toBe('AUTH-100');
    const typed = [line({ id: 'proc', code: '0190', authorisationNumber: 'TYPED-9' }), lines[1]];
    expect(suggestLineAuthorisations(typed, context()).get('mat')).toEqual({ number: 'TYPED-9', authorisationId: null });
  });
});

// Business rule: an authorisation may allow a number of visits (6 physiotherapy sessions); the seventh visit is not
// covered, and a visit already carrying the number counts once, also when it is opened again.
describe('visits allowed', () => {
  const twoVisits = auth({ visitsAllowed: 2 });
  const usage = new Map([['AUTH-100', new Set(['visit-a', 'visit-b'])]]);

  it('stops a new visit once every visit is used, and keeps a visit that already has it', () => {
    expect(authorisationState(twoVisits, '2026-10-12', usage, 'visit-c')).toBe('used_up');
    expect(authorisationState(twoVisits, '2026-10-12', usage, null)).toBe('used_up');
    expect(authorisationState(twoVisits, '2026-10-12', usage, 'visit-a')).toBe('active');
    expect(suggestLineAuthorisations([line()], context({ authorisations: [twoVisits], usage, visitKey: 'visit-c' })).size).toBe(0);
    expect(suggestLineAuthorisations([line()], context({ authorisations: [twoVisits], usage, visitKey: 'visit-b' })).size).toBe(1);
  });

  it('counts each visit once, and not a cancelled invoice', () => {
    const counted = authorisationUsageFrom([
      { number: 'auth-100', visitId: 'v1', cancelled: false },
      { number: 'AUTH-100 ', visitId: 'v1', cancelled: false },
      { number: 'AUTH-100', visitId: 'v2', cancelled: true },
      { number: '', visitId: 'v3', cancelled: false }
    ]);
    expect([...(counted.get('AUTH-100') ?? [])]).toEqual(['v1']);
    expect(counted.size).toBe(1);
  });

  it('counts the visits in the register line', () => {
    expect(describeAuthorisation(twoVisits, usage)).toBe('1 Oct 2026 to 31 Dec 2026 · codes 0190, 0191 · 2 of 2 visits used');
    expect(describeAuthorisation(auth({ allCodes: true, codes: [] }), new Map())).toBe('1 Oct 2026 to 31 Dec 2026 · all codes');
  });
});

// Business rule: a line claimed without the authorisation it needs is refused; staff are told before the claim goes
// that an authorisation ended, has not started or is used up, so they can ask the fund.
describe('warnings', () => {
  it('names an authorisation that ended before the line', () => {
    expect(authorisationNotices([line({ serviceDate: '2027-01-04' })], context())).toEqual([
      'Authorisation AUTH-100 ended on 31 Dec 2026: code 0190 on 4 Jan 2027 is not covered. Ask MAG1 to extend it, or record a new one.'
    ]);
  });

  it('names one that is used up, once however many lines it would cover', () => {
    const usage = new Map([['AUTH-100', new Set(['visit-a'])]]);
    const notices = authorisationNotices([line(), line({ id: 'l2', code: '0191' })], context({ authorisations: [auth({ visitsAllowed: 1 })], usage }));
    expect(notices).toEqual(['Authorisation AUTH-100 is used up: 1 of 1 visits. Ask MAG1 for more visits, or record a new authorisation.']);
  });

  it('says nothing when another authorisation covers the line, or the line is covered', () => {
    const list = [auth({ id: 'old', number: 'OLD-1', validTo: '2026-10-05' }), auth({ id: 'new', number: 'NEW-1', validFrom: '2026-10-06' })];
    expect(authorisationNotices([line()], context({ authorisations: list }))).toEqual([]);
    expect(authorisationNotices([line()], context())).toEqual([]);
  });

  it('names a typed number of the register used outside its window', () => {
    expect(authorisationNotices([line({ authorisationNumber: 'auth-100', serviceDate: '2026-09-01' })], context())[0]).toMatch(/starts on 1 Oct 2026/);
  });
});

// Business rule: what is typed must fit the claim (21 letters or digits in field 31) and say clearly what it covers.
describe('what reception may type for an authorisation', () => {
  it('tidies the fund code and the codes typed', () => {
    const result = validateAuthorisationDraft({ ...emptyAuthorisationDraft(' mag1 ', '2026-10-01'), number: ' A1/2 ', validTo: '2026-12-31', codes: '0190, 0191 0190;0192', visitsAllowed: '6' });
    expect(result).toEqual({
      ok: true,
      value: { fundReference: 'MAG1', number: 'A1/2', validFrom: '2026-10-01', validTo: '2026-12-31', allCodes: false, codes: ['0190', '0191', '0192'], visitsAllowed: 6, note: null, quoteId: null }
    });
  });

  it('refuses a number with spaces, a window back to front, no codes, codes that are not codes and a bad visit count', () => {
    const result = validateAuthorisationDraft({ ...emptyAuthorisationDraft('MAG1', '2026-10-10'), number: 'A 1', validTo: '2026-10-01', visitsAllowed: '0' });
    expect(result.ok).toBe(false);
    if (result.ok) return;
    expect(Object.keys(result.errors).sort()).toEqual(['codes', 'number', 'validTo', 'visitsAllowed']);
    expect(parseCodeList('0190 x-1 0190')).toEqual({ codes: ['0190'], invalid: ['X-1'] });
  });

  it('needs no codes for "all codes"', () => {
    const result = validateAuthorisationDraft({ ...emptyAuthorisationDraft('NMC1', '2026-10-01'), number: 'N1', validTo: '2026-10-31', allCodes: true, codes: '0190' });
    expect(result.ok && result.value.codes).toEqual([]);
  });
});

// Business rule: a quote's pre-authorisation number is what the fund approved for those codes; recording it from the
// quote saves typing it twice, but a number the claim cannot carry is stopped with the reason.
describe('an authorisation from a quote', () => {
  const quote = { id: 'q1', preauthNumber: 'PRE-77', quoteDate: '2026-10-02', validUntil: '2026-11-01', codes: ['8201', '8341', '8201'] };

  it("takes the quote's number, codes and window", () => {
    expect(draftFromQuote(quote, 'MAG1')).toEqual({
      ok: true,
      draft: { fundReference: 'MAG1', number: 'PRE-77', validFrom: '2026-10-02', validTo: '2026-11-01', allCodes: false, codes: '8201, 8341', visitsAllowed: '', note: '', quoteId: 'q1' }
    });
  });

  it('refuses a number the claim cannot carry, or none', () => {
    expect(draftFromQuote({ ...quote, preauthNumber: 'PRE 77' }, 'MAG1')).toMatchObject({ ok: false });
    expect(draftFromQuote({ ...quote, preauthNumber: 'X'.repeat(22) }, 'MAG1')).toMatchObject({ ok: false });
    expect(draftFromQuote({ ...quote, preauthNumber: null }, 'MAG1')).toEqual({ ok: false, message: 'The quote has no pre-authorisation number yet.' });
  });
});
