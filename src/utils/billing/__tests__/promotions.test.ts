import { describe, expect, it } from 'vitest';
import type { ServiceSelection } from '../../../types/billing';
import { parseCodeList } from '../codeList';
import {
  applyPromotions,
  describePromotion,
  draftFromPromotion,
  normalizePromotion,
  promotionDiscountCents,
  promotionFor,
  promotionPayload,
  promotionState,
  syncPromotedLines,
  type Promotion
} from '../promotions';

const SPRING = normalizePromotion({ id: 'promo-1', name: 'Spring smile', kind: 'percent', value: '10.00', codes: ['8261', '0190'], starts_on: '2026-10-01', ends_on: '2026-10-31' }) as Promotion;
const FIFTY = normalizePromotion({ id: 'promo-2', name: 'Fifty off', kind: 'amount', value: 50, codes: ['8262'], starts_on: '2026-10-01', ends_on: '2026-12-31' }) as Promotion;

const line = (overrides: Partial<ServiceSelection> = {}): ServiceSelection => ({
  id: 'line-1',
  tariffId: '2f1e8c7a-1b2c-4d3e-8f90-a1b2c3d4e5f6',
  code: '8261',
  description: 'Invented whitening',
  category: 'Service',
  unitPrice: 1200,
  quantity: 1,
  totalPrice: 1200,
  ...overrides
});

describe('which promotion applies', () => {
  it('covers its codes from its first to its last day, and nothing once an administrator ended it', () => {
    expect(promotionFor([SPRING], '8261', '2026-10-31')?.id).toBe('promo-1');
    expect(promotionFor([SPRING], '8261', '2026-11-01')).toBeNull();
    expect(promotionFor([SPRING], ' 0190 ', '2026-10-01')?.id).toBe('promo-1');
    expect(promotionFor([{ ...SPRING, endedAt: '2026-10-05T10:00:00Z' }], '8261', '2026-10-06')).toBeNull();
    expect(promotionState({ ...SPRING, endedAt: '2026-10-05T10:00:00Z' }, '2026-10-06')).toBe('ended');
    expect(promotionState(SPRING, '2026-09-30')).toBe('upcoming');
  });

  it('takes a percentage of the line, or an amount off each unit, never more than the line', () => {
    expect(promotionDiscountCents(SPRING, 120_000, 1)).toBe(12_000);
    expect(promotionDiscountCents(FIFTY, 30_000, 2)).toBe(10_000);
    expect(promotionDiscountCents(FIFTY, 3_000, 1)).toBe(3_000);
  });

  it('describes itself in words a receptionist reads', () => {
    expect(describePromotion(SPRING)).toBe('10% off 8261, 0190 from 1 Oct 2026 to 31 Oct 2026');
    expect(describePromotion(FIFTY)).toMatch(/^N\$ 50\.00 off each 8262/);
  });
});

describe('applyPromotions on the visit\'s bill', () => {
  const options = { hasMedicalAid: false, visitDateKey: '2026-10-13', lineIds: new Set(['line-1']) };

  it('puts the discount on a private patient\'s new line and names the promotion, so Discounts given can list it', () => {
    const { lines, applied } = applyPromotions([line()], [SPRING], options);
    expect(lines[0].discountAmount).toBe(120);
    expect(lines[0].promotionId).toBe('promo-1');
    expect(applied).toEqual([expect.objectContaining({ lineId: 'line-1', discountCents: 12_000 })]);
  });

  it('never discounts a medical aid line: the fund is claimed at the agreed price', () => {
    const { lines, applied } = applyPromotions([line()], [SPRING], { ...options, hasMedicalAid: true });
    expect(lines[0].discountAmount).toBeUndefined();
    expect(applied).toEqual([]);
  });

  it('leaves a line paid from a package, a line priced by its rule and a discount typed by hand as they are', () => {
    for (const other of [line({ packageId: 'pack-1', unitPrice: 0, totalPrice: 0 }), line({ isAutoGenerated: true }), line({ discountAmount: 30 })]) {
      const { lines } = applyPromotions([other], [SPRING], options);
      expect(lines[0]).toBe(other);
    }
  });

  it('only looks at the lines just added, so opening a saved visit changes nothing', () => {
    const saved = line({ id: 'line-0' });
    const { lines } = applyPromotions([saved], [SPRING], options);
    expect(lines[0]).toBe(saved);
  });

  it('uses the line\'s own date: a line dated after the promotion gets none', () => {
    const { applied } = applyPromotions([line({ serviceDate: '2026-11-02' })], [SPRING], options);
    expect(applied).toEqual([]);
  });
});

describe('syncPromotedLines while the visit is billed', () => {
  const promoted = applyPromotions([line()], [SPRING], { hasMedicalAid: false, visitDateKey: '2026-10-13', lineIds: new Set(['line-1']) }).lines;

  it('leaves a promoted line as it was opened (a later change to the promotion does not change a saved bill)', () => {
    const first = syncPromotedLines(promoted, [{ ...SPRING, percent: 50 }], { hasMedicalAid: false, seen: new Map() });
    expect(first.lines).toBe(promoted);
    expect(first.seen.get('line-1')).toEqual({ discountCents: 12_000, grossCents: 120_000 });
  });

  it('follows the promotion when the quantity changes, so 10% stays 10%', () => {
    const seen = syncPromotedLines(promoted, [SPRING], { hasMedicalAid: false, seen: new Map() }).seen;
    const twice = promoted.map(item => ({ ...item, quantity: 2, totalPrice: 2400 }));
    const next = syncPromotedLines(twice, [SPRING], { hasMedicalAid: false, seen });
    expect(next.lines[0].discountAmount).toBe(240);
    expect(next.lines[0].promotionId).toBe('promo-1');
  });

  it('keeps a discount typed by hand without the promotion\'s name, so the report does not credit the promotion', () => {
    const seen = syncPromotedLines(promoted, [SPRING], { hasMedicalAid: false, seen: new Map() }).seen;
    const typed = promoted.map(item => ({ ...item, discountAmount: 100 }));
    const next = syncPromotedLines(typed, [SPRING], { hasMedicalAid: false, seen });
    expect(next.lines[0].discountAmount).toBe(100);
    expect(next.lines[0].promotionId).toBeUndefined();
  });

  it('takes the discount off when the patient turns out to have a medical aid', () => {
    const next = syncPromotedLines(promoted, [SPRING], { hasMedicalAid: true, seen: new Map() });
    expect(next.lines[0].discountAmount).toBeUndefined();
    expect(next.lines[0].promotionId).toBeUndefined();
  });
});

describe('the administrator\'s form', () => {
  it('reads "10%", codes typed with commas and spaces, and the two days', () => {
    const result = promotionPayload({ name: ' Spring smile ', kind: 'percent', value: '10%', codes: '8261, 0190 8261', startsOn: '2026-10-01', endsOn: '2026-10-31' }, 'practice-1');
    expect(result.error).toBeNull();
    expect(result.payload).toEqual({ id: null, practice_id: 'practice-1', name: 'Spring smile', kind: 'percent', value: 10, codes: ['8261', '0190'], starts_on: '2026-10-01', ends_on: '2026-10-31' });
  });

  it('refuses what the database refuses, in plain words', () => {
    const base = { name: 'Promo', kind: 'percent' as const, value: '10', codes: '0190', startsOn: '2026-10-01', endsOn: '2026-10-31' };
    expect(promotionPayload({ ...base, value: '150' }, 'p').error).toMatch(/at most 100/);
    expect(promotionPayload({ ...base, codes: '01 90!' }, 'p').error).toMatch(/not a tariff code/);
    expect(promotionPayload({ ...base, endsOn: '2026-09-30' }, 'p').error).toMatch(/cannot be before/);
    expect(promotionPayload({ ...base, endsOn: '2029-01-01' }, 'p').error).toMatch(/two years/);
    expect(parseCodeList('', 5).error).toMatch(/at least one code/);
  });

  it('shows a saved promotion in the form as it was saved', () => {
    expect(draftFromPromotion(FIFTY, '2026-10-13', '2026-11-12')).toMatchObject({ kind: 'amount', value: '50.00', codes: '8262' });
  });
});
