/**
 * A material from stock linked to the procedure it was used for (parity D29, NAMAF rule 013: materials are billed at
 * cost plus a handling fee with the procedure). The material line goes straight after its procedure (after the
 * procedure's own automatic lines, such as 8346), takes the procedure's date, practitioner, tooth, who pays, the fund's
 * authorisation number and referral, so its claim line travels with the procedure, and says on the invoice what it was
 * used for ("Used for 8341, tooth 16").
 */
import type { ServiceSelection } from '../../types/billing';

export interface ProcedureOption {
  id: string;
  label: string;
}

const toothText = (line: Pick<ServiceSelection, 'teethNumbers'>): string | null => {
  const teeth = (line.teethNumbers ?? []).map(tooth => tooth.trim()).filter(Boolean);
  if (teeth.length === 0) return null;
  return teeth.length === 1 ? `tooth ${teeth[0]}` : `teeth ${teeth.join(', ')}`;
};

/** The bill's lines a material can be used for: not stock items themselves, not automatic lines */
export function procedureOptions(lines: readonly ServiceSelection[], stockItemIds: ReadonlySet<string>): ProcedureOption[] {
  return lines
    .filter(line => !stockItemIds.has(line.tariffId) && !line.isAutoGenerated)
    .map(line => {
      const tooth = toothText(line);
      return { id: line.id, label: [line.code, tooth, line.description].filter(Boolean).join(' · ').slice(0, 90) };
    });
}

/** "Used for 8341, tooth 16" */
export function usedForNote(procedure: Pick<ServiceSelection, 'code' | 'teethNumbers'>): string {
  const tooth = toothText(procedure);
  return `Used for ${procedure.code}${tooth ? `, ${tooth}` : ''}`;
}

/**
 * The bill with the material added: linked to `procedureId` and placed after it, or at the end when it is used for
 * nothing in particular (or the procedure is no longer on the bill).
 */
export function addMaterialLine(lines: readonly ServiceSelection[], material: ServiceSelection, procedureId: string | null): ServiceSelection[] {
  const at = procedureId ? lines.findIndex(line => line.id === procedureId) : -1;
  if (at < 0) return [...lines, material];
  const procedure = lines[at];
  let after = at;
  while (after + 1 < lines.length && lines[after + 1].parentServiceId === procedure.id) after += 1;
  const linked: ServiceSelection = {
    ...material,
    parentServiceId: procedure.id,
    ...(procedure.serviceDate ? { serviceDate: procedure.serviceDate } : {}),
    ...(procedure.practitionerId ? { practitionerId: procedure.practitionerId } : {}),
    ...(procedure.teethNumbers?.length ? { teethNumbers: [...procedure.teethNumbers] } : {}),
    ...(procedure.paidBy ? { paidBy: procedure.paidBy } : {}),
    ...(procedure.authorisationNumber ? { authorisationNumber: procedure.authorisationNumber } : {}),
    ...(procedure.referralId ? { referralId: procedure.referralId } : {}),
    notes: material.notes?.trim() ? material.notes : usedForNote(procedure)
  };
  return [...lines.slice(0, after + 1), linked, ...lines.slice(after + 1)];
}
