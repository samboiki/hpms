import { describe, expect, it } from 'vitest';
import type { ServiceSelection } from '../../../types/billing';
import { addMaterialLine, procedureOptions, usedForNote } from '../materialLines';

const line = (overrides: Partial<ServiceSelection>): ServiceSelection => ({
  id: 'x',
  tariffId: 'tariff',
  code: '0000',
  description: 'Invented',
  category: 'Service',
  unitPrice: 100,
  quantity: 1,
  totalPrice: 100,
  ...overrides
});

const filling = line({ id: 'proc', code: '8341', description: 'Resin filling', teethNumbers: ['16'], serviceDate: '2026-10-12', practitionerId: 'dr-1', paidBy: 'fund', authorisationNumber: 'AUTH1' });
const factor = line({ id: 'factor', code: '8346', isAutoGenerated: true, parentServiceId: 'proc' });
const exam = line({ id: 'exam', code: '8101' });
const material = line({ id: 'mat', tariffId: 'item-1', code: '0201', description: 'Composite', category: 'Stock' });

describe('a material linked to its procedure (NAMAF rule 013)', () => {
  it('goes straight after the procedure and its 8346, so the fund reads it with the procedure', () => {
    const bill = addMaterialLine([filling, factor, exam], material, 'proc');
    expect(bill.map(item => item.id)).toEqual(['proc', 'factor', 'mat', 'exam']);
  });

  it('takes the procedure\'s day, practitioner, tooth, payer and authorisation, and says on the invoice what it was for', () => {
    const linked = addMaterialLine([filling], material, 'proc')[1];
    expect(linked).toMatchObject({
      parentServiceId: 'proc',
      serviceDate: '2026-10-12',
      practitionerId: 'dr-1',
      teethNumbers: ['16'],
      paidBy: 'fund',
      authorisationNumber: 'AUTH1',
      notes: 'Used for 8341, tooth 16'
    });
  });

  it('goes at the end, unlinked, when it was used for nothing in particular or the procedure is gone', () => {
    expect(addMaterialLine([filling, exam], material, null).map(item => item.id)).toEqual(['proc', 'exam', 'mat']);
    expect(addMaterialLine([exam], material, 'proc')[1].parentServiceId).toBeUndefined();
  });

  it('offers the bill\'s procedures, not stock lines or automatic lines', () => {
    const options = procedureOptions([filling, factor, exam, material], new Set(['item-1']));
    expect(options.map(option => option.id)).toEqual(['proc', 'exam']);
    expect(options[0].label).toBe('8341 · tooth 16 · Resin filling');
  });

  it('names several teeth in the note', () => {
    expect(usedForNote({ code: '8301', teethNumbers: ['11', '12'] })).toBe('Used for 8301, teeth 11, 12');
  });
});
